/// The server-transaction id of a request: its top Via's branch and
/// sent-by (RFC 3261 §17.2.3: two hops may well use the same branch).
fn txn_branch(v: &sip_parser::Via<'_>) -> Option<Arc<[u8]>> {
    let b = v.branch?;
    // ":port", formatted on the stack.
    let mut port = [0u8; 6];
    let mut port_len = 0;
    if let Some(mut p) = v.port {
        let mut digits = [0u8; 5];
        let mut n = 0;
        while let Some(d) = digits.get_mut(n) {
            *d = b'0'.saturating_add(u8::try_from(p % 10).unwrap_or(0));
            n = n.saturating_add(1);
            p /= 10;
            if p == 0 {
                break;
            }
        }
        port[0] = b':';
        for (dst, src) in port.iter_mut().skip(1).zip(digits.iter().take(n).rev()) {
            *dst = *src;
        }
        port_len = n.saturating_add(1);
    }
    // Collected straight into the Arc: every piece has a known length, so
    // this is one allocation (a Vec then `.into()` would be two).
    Some(b.iter().copied().chain(std::iter::once(b'|')).chain(v.host.iter().map(u8::to_ascii_lowercase)).chain(port.iter().take(port_len).copied()).collect())
}

/// When timer tick `n` is due. In u64 milliseconds: a u32 tick count
/// (`TICK * n as u32`) wrapped after 2.7 years of uptime, putting every
/// later deadline in the past.
/// Past what `Instant` can hold (hundreds of millions of years on Linux),
/// the deadline is `start`: the timer loop just doesn't sleep.
fn tick_deadline(start: Instant, n: u64) -> Instant {
    start.checked_add(Duration::from_millis(TICK_MS.saturating_mul(n))).unwrap_or(start)
}

/// Timer ticks for a delay in ms, rounded up. Any u64 works: a delay past
/// the wheel's end of time never fires.
fn ms_to_ticks(ms: u64) -> u64 {
    ms.div_ceil(TICK_MS)
}

/// How long a suspended transaction waits for its resume: the caller's
/// planned delay (async_sleep / async_route, up to u64::MAX ms) plus
/// fr_timer / fr_inv_timer. Saturates: u64::MAX ms is "never".
fn suspend_timeout(extra_ms: u64, fr_ms: u64) -> u64 {
    extra_ms.saturating_add(fr_ms)
}

/// Whether the extra header lines of a `t_uac` request (`Name: value`,
/// one per line) include header `name` (case-insensitive). Byte-wise, so
/// a non-ASCII header name never splits a character.
fn has_header_line(headers: &str, name: &str) -> bool {
    let name = name.as_bytes();
    headers.lines().map(str::as_bytes).any(|l| l.get(..name.len()).is_some_and(|p| p.eq_ignore_ascii_case(name)) && l.get(name.len()) == Some(&b':'))
}

/// Random per process, in every branch we create: branches must be unique
/// across space and time (RFC 3261 §8.1.1.7), also across restarts and
/// between ferrosip instances whose counters start alike.
#[allow(clippy::cast_possible_truncation, reason = "the nonce is the low 32 bits of a hash")]
fn branch_nonce() -> u32 {
    static N: std::sync::OnceLock<u32> = std::sync::OnceLock::new();
    *N.get_or_init(|| {
        let x = clock_seed() ^ (u64::from(std::process::id()) << 32) ^ (&N as *const _ as u64);
        (sip_core::fx_hash(&x.to_le_bytes()) as u32) | 1
    })
}

fn via_line(proto: Proto, local: SocketAddr, branch: &[u8]) -> Vec<u8> {
    let mut v = Vec::with_capacity(80);
    let _ = write!(v, "Via: SIP/2.0/{} {local};branch=", proto.via_name());
    v.extend_from_slice(branch);
    v.extend_from_slice(b"\r\n");
    v
}

/// Reply to the stored original request (local 408/477/100…).
fn synth(req: &[u8], code: u16, reason: &str) -> Option<Vec<u8>> {
    let arena = Bump::new();
    let mut m = Msg::parse(req, &arena).ok()?;
    trying_or_reply(&mut m, code, reason)
}

/// A reply built from an already-parsed request, sized once (a reply copies
/// a subset of the request's headers plus a status line, a To-tag and
/// Content-Length), so building it doesn't regrow the buffer.
fn trying_or_reply(m: &mut Msg<'_>, code: u16, reason: &str) -> Option<Vec<u8>> {
    let mut out = Vec::with_capacity(m.buf.len().min(16 * 1024).saturating_add(128));
    build_reply(m, code, reason, &mut out).ok()?;
    Some(out)
}

/// RFC 3261 §16.7 step 6: rank for choosing the best final response.
fn rank(code: u16) -> (u8, u8) {
    match code {
        600..=699 => (0, 0),
        300..=399 => (1, 0),
        401 | 407 | 415 | 420 | 484 => (2, 0), // resubmission hints first
        400..=499 => (2, 1),
        500..=599 => (3, 0),
        _ => (9, 0),
    }
}

/// Header lines named `name` (case-insensitive) in a message's header section.
fn header_lines<'a>(msg: &'a [u8], name: &[u8]) -> Vec<&'a [u8]> {
    let head = memfind(msg, b"\r\n\r\n").and_then(|end| msg.get(..end)).unwrap_or(msg);
    head.split(|&c| c == b'\n')
        .filter(|l| l.split_at_checked(name.len()).is_some_and(|(n, rest)| n.eq_ignore_ascii_case(name) && rest.first() == Some(&b':')))
        .map(|l| l.strip_suffix(b"\r").unwrap_or(l))
        .collect()
}

/// Index into `TmStats::class` / `TmTimes::txn` of a final status code
/// (2xx..6xx).
fn class_index(code: u16) -> Option<usize> {
    usize::from(code / 100).checked_sub(2).filter(|&k| k < 5)
}

/// `want_args`, as an array to destructure.
