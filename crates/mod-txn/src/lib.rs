const TIMED_FINAL: u8 = 1;
const TIMED_FIRST: u8 = 2;

/// Latency histograms: transaction time by (INVITE/other, reply class),
/// and the INVITE's first reply after 100 (post-dial delay).
struct TmTimes {
    txn: [[&'static sip_core::stats::Histogram; 5]; 2],
    first: &'static sip_core::stats::Histogram,
}

fn times() -> &'static TmTimes {
    static T: OnceLock<TmTimes> = OnceLock::new();
    T.get_or_init(|| {
        use sip_core::stats::{buckets, histogram};
        let h = |m: &str, c: &str| {
            histogram("tm_transaction_seconds", "Request in to final reply out, by method and reply class", &[("method", m), ("class", c)], buckets::TXN)
        };
        let classes = ["2xx", "3xx", "4xx", "5xx", "6xx"];
        TmTimes {
            txn: [classes.map(|c| h("INVITE", c)), classes.map(|c| h("other", c))],
            first: histogram("tm_invite_first_reply_seconds", "INVITE in to its first reply above 100 out (post-dial delay)", &[], buckets::TXN),
        }
    })
}

fn label_of(handle: u64) -> u64 {
    handle.wrapping_mul(0x9E37_79B1) & 0xFFFF_FFFF
}

fn code_of(reply: &[u8]) -> u16 {
    reply.get(8..11).and_then(|c| std::str::from_utf8(c).ok()?.parse().ok()).unwrap_or(0)
}

impl Txn {
    /// A final reply made here (not a branch's) to send upstream; then
    /// `event_route[tm:local-response]`.
    fn local_reply_upstream(&mut self, reply: Arc<[u8]>, io: &mut Vec<Io>) {
        self.reply_upstream(reply.clone(), true, io);
        if !self.local {
            io.push(Io::LocalOut(reply, Box::new(self.vars.clone())));
        }
    }

    /// Send a reply towards the originator: upstream, or — for local
    /// requests — the completion callback (finals only).
    fn reply_upstream(&mut self, reply: impl Into<Arc<[u8]>>, is_final: bool, io: &mut Vec<Io>) {
        let r: Arc<[u8]> = reply.into();
        let c = code_of(&r);
        if is_final && let Some(class) = class_index(c).and_then(|k| st().class.get(k)) {
            sip_core::stats::inc(class);
        }
        // Latency, once per transaction (INVITE 2xx retransmissions and
        // forked 2xx come through here again).
        if !self.local && c > 100 && self.timed & (TIMED_FINAL | TIMED_FIRST) != TIMED_FINAL | TIMED_FIRST {
            let t = self.created.elapsed();
            let invite = self.method == Method::Invite;
            if invite && self.timed & TIMED_FIRST == 0 {
                self.timed |= TIMED_FIRST;
                times().first.observe(t);
            }
            if is_final
                && self.timed & TIMED_FINAL == 0
                && let Some(h) = times().txn.get(usize::from(!invite)).zip(class_index(c)).and_then(|(row, k)| row.get(k))
            {
                self.timed |= TIMED_FINAL | TIMED_FIRST;
                h.observe(t);
            }
        }
        if !self.local {
            sip_core::stats::inc(st().rpl_sent);
            io.push(Io::Send(self.upstream, r.clone()));
            if HOOKS.load(Ordering::Relaxed) {
                io.push(Io::Out(self.upstream, r, self.orig_req.clone().into(), Box::new(self.vars.clone())));
            }
        } else if is_final && let Some(cb) = self.local_cb.take() {
            io.push(Io::Callback(cb, code_of(&r), r));
        }
    }

    /// Key for the transaction's own timers (wait timer).
    fn timer_key(&self) -> Box<[u8]> {
        self.branches.first().map(|b| b.id.clone()).or_else(|| self.timer_id.clone()).unwrap_or_default()
    }

    /// Answer the transaction ourselves (suspended, or a failure route left
    /// nothing to forward).
    fn local_final(&mut self, code: u16, reason: &str, wait: u64, io: &mut Vec<Io>) {
        if self.final_sent {
            return;
        }
        sip_core::stats::inc(st().rpl_generated);
        let Some(r) = synth(&self.orig_req, code, reason) else { return };
        let r: Arc<[u8]> = r.into();
        self.final_sent = true;
        self.local_reply_upstream(r.clone(), io);
        self.last_reply = Some(r);
        io.push(Io::Timer(wait, TimerKind::Wait, self.timer_key()));
    }

    /// CANCEL branch `i` (RFC 3261 §9.1): a client transaction of its own,
    /// retransmitted over UDP until answered, abandoned after 64·T1.
    fn send_cancel(&mut self, i: usize, net: &dyn Outbound, io: &mut Vec<Io>) {
        let Some(b) = self.branches.get(i) else { return };
        let adv = net.advertise(b.dst.proto).unwrap_or_else(|| SocketAddr::from(([127, 0, 0, 1], 5060)));
        let m: Arc<[u8]> = self.cancel_msg(b, adv).into();
        let t1 = self.t1;
        let Some(b) = self.branches.get_mut(i) else { return };
        b.cancel_sent = true;
        b.cancel_req = Some(m.clone());
        io.push(Io::Send(b.dst, m));
        if b.dst.proto == Proto::Udp {
            b.cancel_rt = t1;
            io.push(Io::Timer(t1, TimerKind::CancelRetransmit, b.id.clone()));
        }
        io.push(Io::Timer(t1.saturating_mul(64), TimerKind::CancelTimeout, b.id.clone()));
    }

    fn cancel_msg(&self, b: &Branch, adv: SocketAddr) -> Vec<u8> {
        let mut c = Vec::with_capacity(self.cancel_hdrs.len().saturating_add(256));
        c.extend_from_slice(b"CANCEL ");
        c.extend_from_slice(&b.ruri);
        c.extend_from_slice(b" SIP/2.0\r\n");
        c.extend_from_slice(&via_line(b.dst.proto, adv, &b.id));
        c.extend_from_slice(&self.cancel_hdrs);
        c.extend_from_slice(b"Max-Forwards: 70\r\nContent-Length: 0\r\n\r\n");
        c
    }

    /// Stop forking: CANCEL ringing branches; branches still waiting for a
    /// provisional get theirs when it arrives (§9.1); queued ones are dropped.
    fn cancel_all(&mut self, except: Option<usize>, net: &dyn Outbound, io: &mut Vec<Io>) {
        self.canceled = true;
        if self.method != Method::Invite {
            return;
        }
        for i in 0..self.branches.len() {
            if Some(i) == except {
                continue;
            }
            let Some(b) = self.branches.get_mut(i) else { continue };
            match b.state {
                BState::Proceeding if !b.cancel_sent => self.send_cancel(i, net, io),
                BState::Pending => b.state = BState::Completed,
                _ => {}
            }
        }
    }

    /// Branch `i` failed over to its next unblocked address; false (and
    /// nothing changed but `alts`) if there is none left — another thread
    /// may have blocklisted it since the caller looked.
    fn failover(&mut self, i: usize, net: &dyn Outbound, io: &mut Vec<Io>) -> bool {
        let Some(old) = self.branches.get_mut(i) else { return false };
        old.alts.retain(|d| !sip_core::blst::blocklist().is_blocked(d));
        let Some((&nd, rest)) = old.alts.split_first() else { return false };
        let alts = rest.to_vec();
        old.alts = Vec::new();
        old.state = BState::Completed;
        old.code = 0; // replaced, not aggregated
        let n = self.branches.len();
        let Some(old) = self.branches.get(i) else { return false };
        let mut id = old.id.to_vec();
        let _ = write!(id, ".{n}");
        let id: Box<[u8]> = id.into();
        // Same request, new Via (transport, address and branch may change).
        let adv_old = net.advertise(old.dst.proto).unwrap_or_else(|| SocketAddr::from(([127, 0, 0, 1], 5060)));
        let adv_new = net.advertise(nd.proto).unwrap_or_else(|| SocketAddr::from(([127, 0, 0, 1], 5060)));
        let (from, to) = (via_line(old.dst.proto, adv_old, &old.id), via_line(nd.proto, adv_new, &id));
        let req: Vec<u8> = memfind(&old.req_out, &from)
            .and_then(|p| old.req_out.split_at_checked(p))
            .and_then(|(head, tail)| Some([head, to.as_slice(), tail.strip_prefix(from.as_slice())?].concat()))
            .unwrap_or_else(|| old.req_out.to_vec());
        let b = Branch {
            id: id.clone(),
            dst: nd,
            ruri: old.ruri.clone(),
            req_out: req.into(),
            group: old.group,
            state: BState::Pending,
            rt_ms: self.t1,
            fr_inv_armed: false,
            cancel_sent: false,
            code: 0,
            reply: None,
            local: false,
            alts,
            cancel_req: None,
            cancel_rt: 0,
            ack: None,
        };
        self.branches.push(b);
        io.push(Io::Map(id, self.skey.clone()));
        self.start_branch(n, io);
        true
    }

    fn start_branch(&mut self, i: usize, io: &mut Vec<Io>) {
        let Some(b) = self.branches.get_mut(i) else { return };
        b.state = BState::Calling;
        io.push(send_io(b.dst, b.req_out.clone()));
        if b.dst.proto == Proto::Udp {
            io.push(Io::Timer(self.t1, TimerKind::Retransmit, b.id.clone()));
        }
        io.push(Io::Timer(self.fr, TimerKind::FinalResponse, b.id.clone()));
    }

    /// A branch reached a final state (received, timed out or failed).
    fn on_final(&mut self, i: usize, code: u16, reply: Arc<[u8]>, wait: u64, net: &dyn Outbound, io: &mut Vec<Io>) {
        self.on_final_x(i, code, reply, false, wait, net, io)
    }

    /// Same, for a final we generated ourselves.
    fn on_local_final(&mut self, i: usize, code: u16, reason: &str, wait: u64, net: &dyn Outbound, io: &mut Vec<Io>) {
        sip_core::stats::inc(st().rpl_generated);
        let r = synth(&self.orig_req, code, reason).unwrap_or_default();
        self.on_final_x(i, code, r.into(), true, wait, net, io)
    }

    #[allow(clippy::too_many_arguments, reason = "one final reply: branch, code, bytes, origin, wait, and the output sinks")]
    fn on_final_x(&mut self, i: usize, code: u16, reply: Arc<[u8]>, local: bool, wait: u64, net: &dyn Outbound, io: &mut Vec<Io>) {
        let Some(b) = self.branches.get(i) else { return };
        if b.state == BState::Completed {
            return;
        }
        let blst = sip_core::blst::blocklist();
        if blst.enabled.load(Ordering::Relaxed) {
            if local && (code == 477 || code == 408 && b.state == BState::Calling) {
                // Send failure, or no reply at all.
                blst.add(&b.dst, None);
            } else if !local && code == 503 && blst.on_503.load(Ordering::Relaxed) {
                let ra = header_lines(&reply, b"Retry-After")
                    .first()
                    .and_then(|l| std::str::from_utf8(l.get(b"Retry-After:".len()..)?).ok()?.trim().split([' ', ';', '(']).next()?.parse::<u64>().ok());
                let def = blst.def_503.load(Ordering::Relaxed);
                if let Some(secs) = ra.or((def > 0).then_some(def)) {
                    blst.add(&b.dst, Some(secs));
                }
            }
        }
        // RFC 3263 §4.3: 503, a timeout or a send failure → the next address
        // of the same DNS name, as a new client transaction.
        // Kamailio t_fwd.c add_uac_dns_fallback(): not beyond max_branches.
        if b.alts.iter().any(|d| !blst.is_blocked(d))
            && self.used_slots() < self.max_br
            && !self.canceled
            && !self.final_sent
            && (code == 503 || (local && matches!(code, 408 | 477)))
            && self.failover(i, net, io)
        {
            return;
        }
        let Some(b) = self.branches.get_mut(i) else { return };
        b.state = BState::Completed;
        b.code = code;
        b.local = local;
        b.reply = Some(reply.clone());
        let id = b.id.clone();
        if (200..300).contains(&code) {
            // Every 2xx to an INVITE goes upstream (each may create a dialog);
            // for other methods only the first one.
            if self.method == Method::Invite || !self.final_sent {
                self.reply_upstream(reply.clone(), true, io);
            }
            if !self.final_sent {
                self.final_sent = true;
                self.last_reply = Some(reply);
                io.push(Io::Timer(wait, TimerKind::Wait, id));
                // `await`: the code after it runs too (it can't reply now).
                if self.awaiting.is_some() {
                    io.push(Io::Failure(self.skey.clone()));
                }
            }
            self.cancel_all(Some(i), net, io);
            return;
        }
        if code >= 600 {
            self.cancel_all(Some(i), net, io);
        }
        self.check_done(wait, net, io);
    }

    /// All branches of the current group final → next q-group, or send the
    /// best response upstream.
    fn check_done(&mut self, wait: u64, _net: &dyn Outbound, io: &mut Vec<Io>) {
        if self.final_sent || self.in_failure || self.branches.iter().any(|b| matches!(b.state, BState::Calling | BState::Proceeding)) {
            return;
        }
        let six = self.branches.iter().any(|b| b.code >= 600);
        if !self.canceled
            && !six
            && let Some(g) = self.branches.iter().find(|b| b.state == BState::Pending).map(|b| b.group)
        {
            self.group = g;
            let group: Vec<usize> = self.branches.iter().enumerate().filter(|(_, b)| b.state == BState::Pending && b.group == g).map(|(i, _)| i).collect();
            for i in group {
                self.start_branch(i, io);
            }
            return;
        }
        // Kamailio: a failed transaction first goes through its failure_route,
        // which may fork again (t_relay) or answer (t_reply). It runs after
        // the caller's CANCEL too (`t_is_canceled` is for that); only new
        // branches are refused then.
        if self.on_failure.is_some() || self.awaiting.is_some() {
            self.in_failure = true;
            io.push(Io::Failure(self.skey.clone()));
            return;
        }
        self.send_best(wait, io);
    }

    fn send_best(&mut self, wait: u64, io: &mut Vec<Io>) {
        let (reply, remapped) = self.best_reply();
        let reply: Arc<[u8]> = reply.into();
        self.final_sent = true;
        // Our own 408/487/477 (no real final won).
        if self.best().is_none_or(|b| b.local) {
            self.local_reply_upstream(reply.clone(), io);
        } else {
            if remapped {
                sip_core::stats::inc(st().rpl_generated);
            }
            self.reply_upstream(reply.clone(), true, io);
        }
        self.last_reply = Some(reply);
        io.push(Io::Timer(wait, TimerKind::Wait, self.timer_key()));
    }

    /// Index of the best final response (RFC 3261 §16.7 step 6); real
    /// responses beat our own timeouts/failures of the same rank.
    fn best_index(&self) -> Option<usize> {
        let done = self.branches.iter().enumerate().filter(|(_, b)| b.code >= 300 && b.reply.is_some());
        done.min_by_key(|(_, b)| (rank(b.code), b.local)).map(|(i, _)| i)
    }

    /// The branch of `best_index()`.
    fn best(&self) -> Option<&Branch> {
        self.best_index().and_then(|i| self.branches.get(i))
    }

    /// Branch slots taken: `branches` + `blind` (compared with `max_br`).
    fn used_slots(&self) -> usize {
        self.branches.len().saturating_add(self.blind)
    }

    /// The reply to send upstream, and whether it is a 503 answered with
    /// our own 500.
    fn best_reply(&self) -> (Vec<u8>, bool) {
        let done: Vec<&Branch> = self.branches.iter().filter(|b| b.code >= 300 && b.reply.is_some()).collect();
        let canceled = self.upstream_canceled && self.method == Method::Invite;
        let best = self.best();
        // Canceled by the caller and no real final came back: 487.
        if canceled && best.is_none_or(|b| b.local) {
            return (synth(&self.orig_req, 487, "Request Terminated").unwrap_or_default(), false);
        }
        // best_index() only picks branches with a reply.
        let Some((best, best_raw)) = best.and_then(|b| Some((b, b.reply.as_deref()?))) else {
            return (synth(&self.orig_req, 408, "Request Timeout").unwrap_or_default(), false);
        };
        if best.code == 503 && !best.local && !self.local {
            // §16.7 step 6: a 503 must not be forwarded (it would make the
            // upstream think *we* are overloaded). As Kamailio (t_reply.c
            // relay_reply(), remap_503_500): a new 500 built from the
            // request, with the 503's reason text "Service Unavailable"
            // (error_text(503)); nothing of the 503 is copied. Local
            // transactions (t_uac) get the 503 itself (local_reply()).
            return (synth(&self.orig_req, 500, "Service Unavailable").unwrap_or_default(), true);
        }
        let mut r = best_raw.to_vec();
        if matches!(best.code, 401 | 407) {
            // §16.7 step 7: merge the challenges of all 401/407 branches.
            let mut extra = Vec::new();
            for b in done.iter().filter(|b| !std::ptr::eq(**b, best) && matches!(b.code, 401 | 407)) {
                let reply = b.reply.as_deref().unwrap_or_default();
                for name in [&b"WWW-Authenticate"[..], b"Proxy-Authenticate"] {
                    for l in header_lines(reply, name) {
                        extra.extend_from_slice(l);
                        extra.extend_from_slice(b"\r\n");
                    }
                }
            }
            // After the last header line's CRLF.
            if let Some(at) = memfind(&r, b"\r\n\r\n").and_then(|eoh| eoh.checked_add(2)) {
                r.splice(at..at, extra);
            }
        }
        (r, false)
    }
}

impl Tm {
    fn schedule(&self, worker: usize, delay_ms: u64, kind: TimerKind, branch: &[u8]) {
        self.schedule_cmd(worker, TimerCmd { delay_ms, kind, branch: branch.into() });
    }

    /// Hand a timer to the timer thread (the command's branch id is moved,
    /// not copied).
    fn schedule_cmd(&self, worker: usize, cmd: TimerCmd) {
        #[allow(clippy::indexing_slicing, reason = "`inbox` has INBOXES entries, so `worker % INBOXES` is in bounds")]
        lock(&self.inbox[worker % INBOXES]).push(cmd);
    }

    fn net(&self) -> Option<&Arc<dyn Outbound>> {
        self.net.get()
    }

    /// Send a request of our own (Kamailio `t_uac`): a client transaction
    /// with UDP retransmissions and fr_timer; the final reply (or a local
    /// 408/477) goes to `cb`. INVITE is not supported (it would need an ACK
    /// for 2xx and dialog handling).
    /// The server transaction of the current request, if tm created one.
    pub fn txn_of(&self, ctx: &Ctx<'_, '_>) -> Option<TxnId> {
        let branch = ctx.msg.via1.and_then(|v| txn_branch(&v))?;
        let key: ServerKey = (branch, ctx.msg.method()?);
        self.txns.with(&key, |_| ()).map(|_| TxnId(key))
    }

    /// The request of the transaction a reply belongs to (onreply_route;
    /// e.g. ims_ipsec_pcscf reads the REGISTER's Security-Client).
    pub fn request_of_reply(&self, ctx: &mut Ctx<'_, '_>) -> Option<Vec<u8>> {
        ctx.msg.parse_headers(HdrFlags::VIA).ok()?;
        let b = ctx.msg.via1.and_then(|v| v.branch)?;
        let skey = self.by_branch.get_cloned(b)?;
        self.txns.with(&skey, |t| t.orig_req.clone())
    }

    /// tmx `t_is_failure_route()`.
    pub fn in_failure_route(ctx: &Ctx<'_, '_>) -> bool {
        ctx.ext::<InFailure>().is_some()
    }

    /// tmx `t_is_branch_route()`.
    pub fn in_branch_route(ctx: &Ctx<'_, '_>) -> bool {
        ctx.ext::<InBranchRoute>().is_some()
    }

    /// The transaction still waits for its final reply.
    pub fn txn_pending(&self, id: &TxnId) -> bool {
        self.txns.with(&id.0, |t| !t.final_sent).unwrap_or(false)
    }

    /// Add a branch to a running transaction (tsilo: a client registered
    /// while its INVITE was ringing elsewhere). Uses the original request
    /// with `uri` as R-URI, `dst` as next hop and `path` as Route set.
    pub fn append_branch(&self, id: &TxnId, uri: Vec<u8>, dst: Option<Dest>, path: Option<Vec<u8>>) -> bool {
        let Some(net) = self.net().cloned() else { return false };
        let Some((req, upstream, vars, group, used, pending)) =
            self.txns.with(&id.0, |t| (t.orig_req.clone(), t.upstream, t.vars.clone(), t.group, t.used_slots(), !t.final_sent && !t.canceled))
        else {
            return false;
        };
        if !pending {
            return false;
        }
        let Some((dst, alts)) = dst.map(|d| (d, Vec::new())).or_else(|| self.ruri_dests(&uri)) else { return false };
        let arena = Bump::new();
        let Ok(mut msg) = Msg::parse(&req, &arena) else { return false };
        let (mut lumps, mut out) = (Lumps::default(), Vec::new());
        let mut ctx = Ctx::new(&mut msg, &mut lumps, &mut out, &*net, None, upstream, 0);
        ctx.ext.push(Box::new(vars));
        ctx.new_ruri = Some(uri);
        if let Some(p) = path {
            ctx.ext.push(Box::new(sip_core::module::RuriPath(p)));
        }
        let new = self.build_branches(&mut ctx, dst, alts, group, sip_core::module::max_branches().saturating_sub(used));
        if new.is_empty() {
            return false;
        }
        for b in &new {
            self.by_branch.insert(b.id.clone(), id.0.clone());
        }
        let mut io = Vec::new();
        let ok = self.txns.with(&id.0, |t| {
            if t.final_sent {
                return false;
            }
            let (first, group) = (t.branches.len(), t.group);
            t.branches.extend(new.into_iter().map(|b| Branch { group, ..b }));
            for i in first..t.branches.len() {
                t.start_branch(i, &mut io);
            }
            true
        });
        if ok != Some(true) {
            return false;
        }
        self.exec(io, &*net, 0, &mut |d, m| drop(net.send(d, m)), &mut |c| self.schedule_cmd(0, c));
        true
    }

    /// Suspend the current request (Kamailio `t_suspend`): a transaction
    /// without branches that absorbs retransmissions (INVITE: 100 Trying)
    /// and answers a CANCEL with 487, until `resume`. After `fr_timer`
    /// (`fr_inv_timer` for INVITE) without a relay or reply it answers 500.
    /// `Err(0)`: a retransmission of a request we already hold (absorbed —
    /// the script should stop); `Err(-1)`: can't suspend here.
    pub fn suspend(&self, ctx: &mut Ctx<'_, '_>) -> Result<TxnId, i32> {
        self.suspend_for(ctx, 0)
    }

    /// `suspend`, with `extra_ms` added to the timeout (the planned delay
    /// of async_route / async_sleep).
    pub fn suspend_for(&self, ctx: &mut Ctx<'_, '_>, extra_ms: u64) -> Result<TxnId, i32> {
        if ctx.ext.iter().any(|e| e.is::<InFailure>() || e.is::<InBranchRoute>()) || ctx.msg.parse_headers(HdrFlags::VIA).is_err() {
            return Err(-1);
        }
        let method = ctx.msg.method().unwrap_or(Method::Other);
        if matches!(method, Method::Ack | Method::Cancel) {
            return Err(-1);
        }
        let Some(branch) = ctx.msg.via1.and_then(|v| txn_branch(&v)) else { return Err(-1) };
        let skey: ServerKey = (branch.clone(), method);
        let saved = self.save_script_state(ctx);
        // The transaction t_newtran created: suspend it.
        if ctx.ext::<NewTran>().is_some_and(|n| n.skey == skey) {
            let h = self.txns.with(&skey, |t| {
                t.susp = Some(saved);
                t.blind = t.blind.saturating_add(1);
                if t.handle == 0 {
                    t.handle = self.seq.fetch_add(1, Ordering::Relaxed);
                }
                t.handle
            });
            let Some(h) = h else { return Err(-1) };
            self.handles.insert(h, skey.clone());
            *ctx.ext_mut::<SuspendedHandle>() = SuspendedHandle(h);
            return Ok(TxnId(skey));
        }
        // Suspending again while resumed (async_sleep after async_sleep).
        if ctx.ext::<InResume>().is_some_and(|r| r.skey == skey) {
            self.txns.with(&skey, |t| {
                t.susp = Some(saved);
                t.blind = t.blind.saturating_add(1);
            });
            if let Some(r) = ctx.ext_get_mut::<InResume>() {
                r.again = true;
            }
            let h = self.txns.with(&skey, |t| t.handle).unwrap_or(0);
            *ctx.ext_mut::<SuspendedHandle>() = SuspendedHandle(h);
            return Ok(TxnId(skey));
        }
        if let Some(last) = self.txns.with(&skey, |t| t.last_reply.clone().map(|r| (t.upstream, r))) {
            if let Some((up, r)) = last {
                let _ = ctx.send(&up, &r);
            }
            return Err(0);
        }
        let ovr = ctx.ext::<FrOverride>();
        let fr = ovr.and_then(|o| o.fr).unwrap_or(self.fr_timer.load(Ordering::Relaxed));
        let fr_inv = ovr.and_then(|o| o.fr_inv).unwrap_or(self.fr_inv_timer.load(Ordering::Relaxed));
        let cancel_hdrs = cancel_headers(ctx, method);
        let orig_req = ctx.msg.buf.to_vec();
        // From the request as received (already parsed), not a re-parse of the copy.
        let trying: Option<Arc<[u8]>> =
            (method == Method::Invite && self.auto_100.load(Ordering::Relaxed)).then(|| trying_or_reply(ctx.msg, 100, "Trying")).flatten().map(Into::into);
        let handle = self.seq.fetch_add(1, Ordering::Relaxed);
        let mut tid = b"susp.".to_vec();
        tid.extend_from_slice(&branch);
        let tid: Box<[u8]> = tid.into();
        let txn = Txn {
            method,
            created: Instant::now(),
            timed: 0,
            upstream: ctx.reply_dest(),
            orig_req,
            fail_req: Some(saved.req.clone()),
            rr: saved.rr.clone(),
            cancel_hdrs,
            branches: Vec::new(),
            group: 0,
            canceled: false,
            final_sent: false,
            last_reply: trying.clone(),
            fr,
            fr_inv,
            skey: skey.clone(),
            on_failure: saved.arm.0,
            on_reply: saved.arm.1,
            awaiting: None,
            await_ready: false,
            in_failure: false,
            upstream_canceled: false,
            vars: ctx.ext::<TxnVars>().cloned().unwrap_or_default(),
            local: false,
            local_cb: None,
            susp: Some(saved),
            timer_id: Some(tid.clone()),
            handle,
            t1: self.t1.load(Ordering::Relaxed),
            t2: self.t2.load(Ordering::Relaxed),
            blind: 1,
            step: 0,
            max_br: sip_core::module::max_branches(),
        };
        if !self.txns.insert_if_absent(skey.clone(), txn) {
            return Err(0);
        }
        sip_core::stats::inc(st().total);
        self.by_branch.insert(tid.clone(), skey.clone());
        self.handles.insert(handle, skey.clone());
        if let Some(t) = &trying {
            let up = ctx.reply_dest();
            let _ = ctx.send(&up, t);
        }
        self.schedule(ctx.worker, suspend_timeout(extra_ms, if method == Method::Invite { fr_inv } else { fr }), TimerKind::FinalResponse, &tid);
        *ctx.ext_mut::<SuspendedHandle>() = SuspendedHandle(handle);
        Ok(TxnId(skey))
    }

    /// `t_newtran`: the request's server transaction, now (Kamailio). Its
    /// retransmissions are absorbed from here on, whatever the script does
    /// next; relaying adds branches to it, and a reply (stateless included)
    /// becomes its reply. `Err(0)`: a retransmission (its last reply was
    /// sent again); `Err(-1)`: not possible here.
    fn new_tran(self: &Arc<Self>, ctx: &mut Ctx<'_, '_>) -> Result<(), i32> {
        if ctx.ext.iter().any(|e| e.is::<NewTran>() || e.is::<InResume>() || e.is::<InFailure>()) {
            return Ok(());
        }
        if ctx.ext.iter().any(|e| e.is::<InBranchRoute>()) || ctx.msg.parse_headers(HdrFlags::VIA).is_err() {
            return Err(-1);
        }
        let method = ctx.msg.method().unwrap_or(Method::Other);
        if matches!(method, Method::Ack | Method::Cancel) {
            return Err(-1);
        }
        let Some(branch) = ctx.msg.via1.and_then(|v| txn_branch(&v)) else { return Err(-1) };
        let skey: ServerKey = (branch.clone(), method);
        if let Some(last) = self.txns.with(&skey, |t| t.last_reply.clone().map(|r| (t.upstream, r))) {
            if let Some((up, r)) = last {
                let _ = ctx.send(&up, &r);
            }
            return Err(0);
        }
        self.request_in(ctx);
        let ovr = ctx.ext::<FrOverride>();
        let fr = ovr.and_then(|o| o.fr).unwrap_or(self.fr_timer.load(Ordering::Relaxed));
        let fr_inv = ovr.and_then(|o| o.fr_inv).unwrap_or(self.fr_inv_timer.load(Ordering::Relaxed));
        let trying: Option<Arc<[u8]>> =
            (method == Method::Invite && self.auto_100.load(Ordering::Relaxed)).then(|| trying_or_reply(ctx.msg, 100, "Trying")).flatten().map(Into::into);
        // The edits so far; replaced by the request as it is at the first
        // relay or at t_save_lumps() (Kamailio's save_msg_lumps()).
        let fail_req = (!ctx.lumps.is_empty()).then(|| ctx.render_uri(ctx.msg.ruri().map(<[u8]>::to_vec).as_deref()).to_vec());
        let rr = ctx.ext::<sip_core::rr::RecordRoute>().cloned();
        let mut tid = b"newt.".to_vec();
        tid.extend_from_slice(&branch);
        let tid: Box<[u8]> = tid.into();
        let txn = Txn {
            method,
            created: Instant::now(),
            timed: 0,
            upstream: ctx.reply_dest(),
            orig_req: ctx.msg.buf.to_vec(),
            fail_req,
            rr,
            cancel_hdrs: cancel_headers(ctx, method),
            branches: Vec::new(),
            group: 0,
            canceled: false,
            final_sent: false,
            last_reply: trying.clone(),
            fr,
            fr_inv,
            skey: skey.clone(),
            on_failure: None,
            on_reply: None,
            awaiting: None,
            await_ready: false,
            in_failure: false,
            upstream_canceled: false,
            vars: ctx.ext::<TxnVars>().cloned().unwrap_or_default(),
            local: false,
            local_cb: None,
            susp: None,
            timer_id: Some(tid.clone()),
            handle: 0,
            t1: self.t1.load(Ordering::Relaxed),
            t2: self.t2.load(Ordering::Relaxed),
            blind: 0,
            step: 0,
            max_br: sip_core::module::max_branches(),
        };
        if !self.txns.insert_if_absent(skey.clone(), txn) {
            return Err(0);
        }
        sip_core::stats::inc(st().total);
        self.by_branch.insert(tid.clone(), skey.clone());
        if let Some(t) = &trying {
            let up = ctx.reply_dest();
            let _ = ctx.send(&up, t);
        }
        // Nobody relays or answers: the transaction ends with fr_timer.
        self.schedule(ctx.worker, if method == Method::Invite { fr_inv } else { fr }, TimerKind::FinalResponse, &tid);
        // A reply sent the stateless way is the transaction's reply.
        let (me, key, worker) = (self.clone(), skey.clone(), ctx.worker);
        ctx.ext.push(Box::new(sip_core::module::ReplyHook(Arc::new(move |code, msg| {
            let wait = me.wait_timer.load(Ordering::Relaxed);
            let tk = me.txns.with(&key, |t| {
                if t.final_sent {
                    return None;
                }
                t.last_reply = Some(msg.into());
                (code >= 200).then(|| {
                    t.final_sent = true;
                    t.timer_key()
                })
            });
            if let Some(Some(k)) = tk {
                me.schedule(worker, wait, TimerKind::Wait, &k);
            }
        }))));
        ctx.ext.push(Box::new(NewTran { skey, saved: false }));
        Ok(())
    }

    fn save_script_state(&self, ctx: &mut Ctx<'_, '_>) -> Box<Suspended> {
        let arm = ctx.ext::<Arm>().map_or((None, None, None), |a| (a.failure, a.reply, a.branch));
        let fr = ctx.ext::<FrOverride>().map_or((None, None), |o| (o.fr_inv, o.fr));
        let path = ctx.ext::<sip_core::module::RuriPath>().map(|p| p.0.clone());
        Box::new(Suspended {
            req: ctx.render_uri(ctx.msg.ruri().map(<[u8]>::to_vec).as_deref()).to_vec(),
            new_ruri: ctx.new_ruri.clone(),
            dst: ctx.dst,
            ruri_q: ctx.ruri_q,
            branches: ctx.branches.clone(),
            path,
            arm,
            fr,
            rr: ctx.ext::<sip_core::rr::RecordRoute>().cloned(),
        })
    }

    /// A suspended transaction by `$T(id_index)` / `$T(id_label)`.
    pub fn txn_by_handle(&self, index: u64, label: u64) -> Option<TxnId> {
        if label_of(index) != label {
            return None;
        }
        self.handles.get_cloned(&index).map(TxnId)
    }

    /// Resume a suspended transaction: rebuild the request with the
    /// script state it had, run `f` (the continuation) on it, then settle —
    /// a `t_relay()` there forks on this transaction, `t_reply()` or a
    /// stateless reply answers it. False if it is gone, answered or
    /// CANCELed meanwhile.
    pub fn resume(&self, id: &TxnId, f: impl FnOnce(&dyn sip_core::RouteRunner, &mut Ctx<'_, '_>)) -> bool {
        let (Some(net), Some(runner)) = (self.net().cloned(), self.hub.get().and_then(|h| h.runner()).cloned()) else { return false };
        let Some(Some((saved, up, vars))) = self.txns.with(&id.0, |t| {
            if t.final_sent || t.upstream_canceled {
                return None;
            }
            t.susp.take().map(|s| (s, t.upstream, t.vars.clone()))
        }) else {
            return false;
        };
        let arena = Bump::new();
        let Ok(mut msg) = Msg::parse(&saved.req, &arena) else { return false };
        let (mut lumps, mut out) = (Lumps::default(), Vec::new());
        let mut ctx = Ctx::new(&mut msg, &mut lumps, &mut out, &*net, None, up, 0);
        ctx.new_ruri = saved.new_ruri;
        ctx.dst = saved.dst;
        ctx.ruri_q = saved.ruri_q;
        ctx.branches = saved.branches;
        if let Some(p) = saved.path {
            ctx.ext.push(Box::new(sip_core::module::RuriPath(p)));
        }
        ctx.ext.push(Box::new(Arm { failure: saved.arm.0, reply: saved.arm.1, branch: saved.arm.2, awaits: false }));
        ctx.ext.push(Box::new(FrOverride { fr_inv: saved.fr.0, fr: saved.fr.1 }));
        if let Some(rr) = saved.rr {
            ctx.ext.push(Box::new(rr));
        }
        ctx.ext.push(Box::new(vars));
        ctx.ext.push(Box::new(InResume { skey: id.0.clone(), added: false, replied: false, again: false }));
        ctx.ext.push(Box::new(sip_core::module::ReplyCapture(None)));
        let h = self.txns.with(&id.0, |t| t.handle).unwrap_or(0);
        ctx.ext.push(Box::new(SuspendedHandle(h)));
        if sip_core::panic::catch(|| f(&*runner, &mut ctx)).is_err() {
            sip_core::elog!("tm: panic while resuming a suspended request");
        }
        let (added, replied, again) = ctx.ext::<InResume>().map_or((false, false, false), |r| (r.added, r.replied, r.again));
        let vars = ctx.ext::<TxnVars>().cloned().unwrap_or_default();
        let sl = ctx.ext_get_mut::<sip_core::module::ReplyCapture>().and_then(|c| c.0.take());
        let wait = self.wait_timer.load(Ordering::Relaxed);
        let mut io = Vec::new();
        self.txns.with(&id.0, |t| {
            t.vars = vars;
            if added || replied || again || t.final_sent {
                return;
            }
            // Answered statelessly (sl_send_reply): that is the transaction's
            // reply now, for retransmissions too.
            if let Some(r) = sl.filter(|r| code_of(r) >= 200) {
                t.final_sent = true;
                t.last_reply = Some(r.into());
                io.push(Io::Timer(wait, TimerKind::Wait, t.timer_key()));
            }
        });
        self.exec(io, &*net, 0, &mut |d, m| drop(net.send(d, m)), &mut |c| self.schedule_cmd(0, c));
        true
    }

    /// Register a hook for replies sent upstream (dialog, acc…).
    pub fn on_reply_out(&self, h: ReplyHook) {
        write(&self.reply_hooks).push(h);
        HOOKS.store(true, Ordering::Relaxed);
    }

    /// `event_route[tm:local-request]` on a request tm generates itself
    /// (`t_uac`: `t_uac_send`, dialog's BYEs, presence NOTIFYs, …): its
    /// header and body edits are applied before it is sent. `None`: the
    /// route said `drop`, the request is not sent. Not run again for a
    /// request sent from within the route.
    fn local_request(&self, m: Vec<u8>, net: &dyn Outbound, dst: &Dest) -> Option<Vec<u8>> {
        let Some(hub) = self.hub.get() else { return Some(m) };
        let (Some(idx), Some(runner)) = (hub.event_index(EV_LOCAL_REQUEST), hub.runner()) else { return Some(m) };
        if IN_LOCAL_ROUTE.with(|f| f.replace(true)) {
            return Some(m);
        }
        let arena = Bump::new();
        let out = match Msg::parse(&m, &arena) {
            Ok(mut msg) => {
                let (mut lumps, mut out) = (Lumps::default(), Vec::new());
                let src = Dest::new(dst.proto, net.advertise(dst.proto).unwrap_or_else(|| SocketAddr::from(([127, 0, 0, 1], 0))));
                let mut ctx = Ctx::new(&mut msg, &mut lumps, &mut out, net, None, src, 0);
                ctx.dst = Some(*dst);
                ctx.ext.push(Box::new(sip_core::module::FakedMsg));
                match sip_core::panic::catch(|| runner.run_event(idx, &mut ctx)) {
                    Ok(false) => None,
                    Ok(true) if !ctx.lumps.is_empty() => Some(ctx.render_uri(ctx.msg.ruri().map(<[u8]>::to_vec).as_deref()).to_vec()),
                    Ok(true) => Some(m.clone()),
                    Err(_) => {
                        sip_core::elog!("tm: panic in event_route[{EV_LOCAL_REQUEST}]");
                        Some(m.clone())
                    }
                }
            }
            Err(_) => Some(m.clone()),
        };
        IN_LOCAL_ROUTE.with(|f| f.set(false));
        out
    }

    /// `event_route[tm:local-response]`, after tm sent a final reply it
    /// made itself (`t_reply()`, 408 on timeout, 487 after CANCEL, …): as in
    /// Kamailio (t_reply.c `_reply_light()`) it runs on that reply (`$rs`,
    /// `$rr`, its headers); `$T_reply_code` is its status too.
    fn local_response(&self, reply: &[u8], vars: TxnVars, net: &dyn Outbound) {
        let Some(hub) = self.hub.get() else { return };
        if !hub.has_event(EV_LOCAL_RESPONSE) {
            return;
        }
        let code = code_of(reply);
        let ok = sip_core::panic::catch(|| {
            hub.run_event_with(EV_LOCAL_RESPONSE, net, Some(reply), |c| {
                c.ext.push(Box::new(vars));
                c.ext.push(Box::new(LocalReplyCode(code)));
            })
        });
        if ok.is_err() {
            sip_core::elog!("tm: panic in event_route[{EV_LOCAL_RESPONSE}]");
        }
    }

    /// The request line and headers of a local request (`t_uac`).
    fn build_uac(&self, r: &UacRequest, dst: &Dest, adv: SocketAddr, id: &[u8]) -> Vec<u8> {
        let n = self.seq.fetch_add(1, Ordering::Relaxed);
        let has = |h: &str| has_header_line(&r.headers, h);
        let mut m = Vec::with_capacity(r.body.len().saturating_add(512));
        let _ = write!(m, "{} {} SIP/2.0\r\n", r.method, r.ruri);
        m.extend_from_slice(&via_line(dst.proto, adv, id));
        m.extend_from_slice(b"Max-Forwards: 70\r\n");
        if !has("From") {
            let from = r.from.clone().unwrap_or_else(|| format!("sip:ferrosip@{adv}"));
            let _ = write!(m, "From: <{from}>;tag=fs{n:x}\r\n");
        }
        if !has("To") {
            let _ = write!(m, "To: <{}>\r\n", r.to.as_deref().unwrap_or(&r.ruri));
        }
        let call_id = r.call_id.clone().unwrap_or_else(|| format!("fs-{n:x}-{:x}@{}", std::process::id(), adv.ip()));
        let _ = write!(m, "Call-ID: {call_id}\r\nCSeq: {} {}\r\n", r.cseq.max(1), r.method);
        m.extend_from_slice(r.headers.as_bytes());
        if !r.headers.is_empty() && !r.headers.ends_with("\r\n") {
            m.extend_from_slice(b"\r\n");
        }
        let _ = write!(m, "Content-Length: {}\r\n\r\n", r.body.len());
        m.extend_from_slice(&r.body);
        m
    }

    /// Send a request without a transaction (the ACK for a 2xx to a local
    /// INVITE, which the requester sends itself).
    pub fn send_stateless(&self, r: UacRequest) -> Result<(), String> {
        let net = self.net().ok_or("tm not started")?.clone();
        let dst = r.dst.or_else(|| self.ruri_dest(r.ruri.as_bytes())).ok_or_else(|| format!("can't route {}", r.ruri))?;
        let adv = net.advertise(dst.proto).unwrap_or_else(|| SocketAddr::from(([127, 0, 0, 1], 5060)));
        let id = self.new_branch_id(0);
        let m = self.build_uac(&r, &dst, adv, &id);
        let m = self.local_request(m, &*net, &dst).ok_or("dropped by event_route[tm:local-request]")?;
        net.send(&dst, &m).map_err(|e| format!("send to {dst}: {e}"))
    }

    /// Register a hook for requests that get a transaction (dialog's
    /// `dlg_flag`).
    pub fn on_request_in(&self, h: RequestHook) {
        write(&self.request_hooks).push(h);
        REQ_HOOKS.store(true, Ordering::Relaxed);
    }

    fn request_in(&self, ctx: &mut Ctx<'_, '_>) {
        if !REQ_HOOKS.load(Ordering::Relaxed) {
            return;
        }
        let hooks = read(&self.request_hooks).clone();
        for h in hooks {
            h(ctx);
        }
    }

    /// Start a local request (Kamailio `t_uac` / `t_request`). An INVITE
    /// gets an INVITE client transaction: non-2xx finals are ACKed here,
    /// the ACK for a 2xx is up to the caller (`send_stateless`), whose
    /// callback gets the 2xx.
    pub fn t_uac(&self, r: UacRequest, cb: Option<UacCallback>) -> Result<(), String> {
        let method = Method::from_bytes(r.method.as_bytes());
        if method == Method::Ack || method == Method::Cancel {
            return Err(format!("t_uac: {} not supported", r.method));
        }
        let net = self.net().ok_or("tm not started")?.clone();
        let dst = r.dst.or_else(|| self.ruri_dest(r.ruri.as_bytes())).ok_or_else(|| format!("t_uac: can't route {}", r.ruri))?;
        let adv = net.advertise(dst.proto).unwrap_or_else(|| SocketAddr::from(([127, 0, 0, 1], 5060)));
        let id = self.new_branch_id(0);
        let m = self.build_uac(&r, &dst, adv, &id);
        let m = self.local_request(m, &*net, &dst).ok_or("t_uac: dropped by event_route[tm:local-request]")?;
        let cancel_hdrs = if method == Method::Invite { local_cancel_headers(&m) } else { Vec::new() };

        let skey: ServerKey = (Arc::from(&id[..]), method);
        let fr = self.fr_timer.load(Ordering::Relaxed);
        let req: Arc<[u8]> = m.clone().into();
        let txn = Txn {
            method,
            created: Instant::now(),
            timed: 0,
            upstream: dst,
            orig_req: m,
            fail_req: None,
            rr: None,
            cancel_hdrs,
            branches: vec![Branch {
                id: id.clone(),
                dst,
                ruri: r.ruri.into_bytes(),
                req_out: req.clone(),
                group: 0,
                state: BState::Calling,
                rt_ms: self.t1.load(Ordering::Relaxed),
                fr_inv_armed: false,
                cancel_sent: false,
                code: 0,
                reply: None,
                local: false,
                alts: Vec::new(),
                cancel_req: None,
                cancel_rt: 0,
                ack: None,
            }],
            group: 0,
            canceled: false,
            final_sent: false,
            last_reply: None,
            fr,
            fr_inv: self.fr_inv_timer.load(Ordering::Relaxed),
            skey: skey.clone(),
            on_failure: None,
            on_reply: None,
            awaiting: None,
            await_ready: false,
            in_failure: false,
            upstream_canceled: false,
            vars: TxnVars::default(),
            local: true,
            local_cb: cb,
            susp: None,
            timer_id: None,
            handle: 0,
            t1: self.t1.load(Ordering::Relaxed),
            t2: self.t2.load(Ordering::Relaxed),
            blind: 0,
            step: 0,
            max_br: sip_core::module::max_branches(),
        };
        self.txns.insert(skey.clone(), txn);
        sip_core::stats::inc(st().total_local);
        self.by_branch.insert(id.clone(), skey.clone());
        if let Err(e) = net.send(&dst, &req) {
            // Fail through the normal path so the callback still fires.
            let mut io = Vec::new();
            let wait = self.wait_timer.load(Ordering::Relaxed);
            self.txns.with(&skey, |t| t.on_local_final(0, E_SEND.0, E_SEND.1, wait, &*net, &mut io));
            self.exec(io, &*net, 0, &mut |d, m| drop(net.send(d, m)), &mut |c| self.schedule_cmd(0, c));
            return Err(format!("t_uac: send to {dst}: {e}"));
        }
        if dst.proto == Proto::Udp {
            self.schedule(0, self.t1.load(Ordering::Relaxed), TimerKind::Retransmit, &id);
        }
        self.schedule(0, fr, TimerKind::FinalResponse, &id);
        Ok(())
    }

    /// Run the side effects of a locked section.
    fn exec(&self, io: Vec<Io>, net: &dyn Outbound, worker: usize, send: &mut dyn FnMut(&Dest, &[u8]), sched: &mut dyn FnMut(TimerCmd)) {
        let mut failures = Vec::new();
        for a in io {
            match a {
                Io::Send(d, m) => send(&d, &m),
                Io::Map(id, k) => {
                    self.by_branch.insert(id, k);
                }
                Io::Out(d, reply, request, vars) => {
                    let hooks = read(&self.reply_hooks).clone();
                    let out = ReplyOut { reply: &reply, dst: &d, request: &request, vars: &vars };
                    for h in hooks {
                        if sip_core::panic::catch(|| h(&out)).is_err() {
                            sip_core::elog!("tm: panic in a reply hook");
                        }
                    }
                }
                Io::LocalOut(reply, vars) => self.local_response(&reply, *vars, net),
                Io::Timer(delay_ms, kind, branch) => sched(TimerCmd { delay_ms, kind, branch }),
                Io::Failure(k) => failures.push(k),
                Io::Callback(cb, code, r) => {
                    if sip_core::panic::catch(|| cb(code, &r)).is_err() {
                        sip_core::elog!("tm: panic in a local-request callback");
                    }
                }
            }
        }
        for k in failures {
            self.run_failure(&k, net, worker);
        }
    }

    /// Run a transaction's failure_route on a context rebuilt from the
    /// original request (like Kamailio's "faked" request). If the route
    /// neither forks again nor replies, the best response goes upstream.
    fn run_failure(&self, skey: &ServerKey, net: &dyn Outbound, worker: usize) {
        enum Then {
            Route(usize),
            Resume(sip_core::Continuation),
        }
        let runner = self.hub.get().and_then(|h| h.runner()).cloned();
        let mut wait_for_script = false;
        let snap = self
            .txns
            .with(skey, |t| {
                let idx = match (t.on_failure.take(), t.awaiting.take()) {
                    (Some(i), _) => Then::Route(i),
                    (None, Some(Some(c))) => Then::Resume(c),
                    (None, Some(None)) => {
                        // The script hasn't finished unwinding: it resumes
                        // as soon as it has (see `t_relay_await`).
                        t.awaiting = Some(None);
                        t.await_ready = true;
                        wait_for_script = true;
                        return None;
                    }
                    (None, None) => return None,
                };
                // After a 2xx (`await`): that one; else the best negative final.
                let win = t.branches.iter().find(|b| (200..300).contains(&b.code)).or_else(|| t.best());
                let (code, timeout) = win.map_or((408, true), |b| (b.code, b.local && b.code == 408));
                let reply = win.and_then(|b| b.reply.as_deref().map(<[u8]>::to_vec)).unwrap_or_default();
                let req = t.fail_req.clone().unwrap_or_else(|| t.orig_req.clone());
                Some((idx, req, t.upstream, code, timeout, (t.vars.clone(), reply, t.final_sent, t.rr.clone()), (t.branches.len(), t.step)))
            })
            .flatten();
        if wait_for_script {
            return;
        }
        let mode = self.failure_reply_mode.load(Ordering::Relaxed);
        // After the route (Kamailio t_reply.c t_should_relay_response()):
        // the branches before it, the last relay's first one, the drop mode
        // and the relay error.
        let mut after: Option<AfterFailure> = None;
        let arena = Bump::new();
        let (mut lumps, mut out) = (Lumps::default(), Vec::new());
        if let (Some(runner), Some((idx, req, up, code, timeout, (vars, reply, answered, rr), (count, step)))) = (runner, snap) {
            let parsed = Msg::parse(&req, &arena);
            if let Ok(mut msg) = parsed {
                // After a 2xx went upstream, the code after `await` runs
                // with the transaction already answered.
                let failure = InFailure { skey: skey.clone(), code, timeout, added: false, replied: answered, drop: mode, tm_error: None };
                let mut ctx = Ctx::new(&mut msg, &mut lumps, &mut out, net, None, up, worker);
                ctx.ext.push(Box::new(failure));
                if let Some(g) = self.failure_reply_gate(skey, worker) {
                    ctx.ext.push(Box::new(g));
                }
                ctx.ext.push(Box::new(sip_core::module::FakedMsg));
                ctx.ext.push(Box::new(vars));
                ctx.ext.push(Box::new(sip_core::module::FailureReply(reply)));
                if let Some(rr) = rr {
                    ctx.ext.push(Box::new(rr));
                }
                let run = |ctx: &mut Ctx<'_, '_>| match &idx {
                    Then::Route(i) => runner.run_failure(*i, ctx),
                    Then::Resume(c) => {
                        runner.resume(c, ctx);
                    }
                };
                if sip_core::panic::catch(|| run(&mut ctx)).is_err() {
                    sip_core::elog!("tm: panic in failure_route; sending the best reply");
                }
                let (drop, tm_error) = ctx.ext::<InFailure>().map_or((mode, None), |f| (f.drop, f.tm_error));
                after = Some((count, step, drop, tm_error));
                let vars = ctx.ext::<TxnVars>().cloned().unwrap_or_default();
                self.txns.with(skey, |t| t.vars = vars);
            }
        }
        let wait = self.wait_timer.load(Ordering::Relaxed);
        let mut io = Vec::new();
        self.txns.with(skey, |t| {
            t.in_failure = false;
            if t.final_sent {
                return; // answered in the route (or a 2xx before it)
            }
            let Some((count, step, drop, tm_error)) = after else {
                if !t.branches.iter().any(|b| matches!(b.state, BState::Calling | BState::Proceeding)) {
                    t.send_best(wait, &mut io);
                }
                return;
            };
            let added = t.branches.len() > count;
            if drop_replies(t.branches.get_mut(..count).unwrap_or_default(), step, drop, added) && !added {
                // t_reply.c `branches_failed`: nothing left to forward.
                let (code, reason) = tm_error.unwrap_or(E_UNSPEC);
                t.local_final(code, reason, wait, &mut io);
                return;
            }
            // New branches: their finals (some may have come during the
            // route) decide; else the best reply goes upstream.
            t.check_done(wait, net, &mut io);
        });
        self.exec(io, net, worker, &mut |d, m| drop(net.send(d, m)), &mut |c| self.schedule_cmd(worker, c));
    }

    /// One branch per target (R-URI/`dst` first, then the destination set),
    /// rendered with the script's edits, its own R-URI and Via branch. At
    /// most `room`: what `max_branches` leaves of the transaction (Kamailio
    /// t_fwd.c add_uac(): the targets beyond it are dropped).
    fn build_branches(&self, ctx: &mut Ctx<'_, '_>, dst: Dest, alts: Vec<Dest>, group_base: usize, room: usize) -> Vec<Branch> {
        let first_line_end = ctx.msg.first_line_end;
        let main_q = ctx.ruri_q.unwrap_or(1000);
        let main_path = ctx.ext::<sip_core::module::RuriPath>().map(|p| p.0.clone()).filter(|p| !p.is_empty());
        let mut targets: Vec<Target> = vec![(ctx.ruri().to_vec(), dst, main_q, main_path, alts)];
        for b in std::mem::take(&mut ctx.branches) {
            if targets.len() >= room {
                break;
            }
            match b.dst.map(|d| (d, Vec::new())).or_else(|| self.ruri_dests(&b.uri)) {
                Some((d, alts)) => targets.push((b.uri, d, b.q.unwrap_or(1000), b.path, alts)),
                None => sip_core::elog!("tm: dropping unresolvable branch {}", String::from_utf8_lossy(&b.uri)),
            }
        }
        targets.truncate(room);
        // set_forward_no_connect(): branches use open connections only.
        if ctx.ext::<sip_core::module::ForwardNoConnect>().is_some() {
            for t in &mut targets {
                t.1.no_connect = true;
                t.4.iter_mut().for_each(|d| d.no_connect = true);
            }
        }
        // Blocklisted next hops: use another DNS target, or drop the branch.
        let blst = sip_core::blst::blocklist();
        targets.retain_mut(|t| {
            if !blst.is_blocked(&t.1) {
                return true;
            }
            t.4.retain(|d| !blst.is_blocked(d));
            if t.4.is_empty() {
                return false;
            }
            t.1 = t.4.remove(0);
            true
        });
        let by_q = self.fork_by_q.load(Ordering::Relaxed);
        if by_q {
            targets.sort_by_key(|t| std::cmp::Reverse(t.2)); // stable: equal q keep order
        }
        let mut branches = Vec::with_capacity(targets.len());
        let (mut group, mut last_q) = (group_base, None);
        let broute = ctx.ext::<Arm>().and_then(|a| a.branch);
        let runner = broute.and_then(|_| self.hub.get().and_then(|h| h.runner()).cloned());
        for (bi, (uri, d, q, path, mut alts)) in targets.into_iter().enumerate() {
            if by_q && last_q.is_some_and(|lq| lq != q) {
                group = group.saturating_add(1);
            }
            last_q = Some(q);
            let mark = ctx.lumps.len();
            let (mut uri, mut d) = (uri, d);
            // branch_route: per-branch edits ($ru/$du, headers) or `drop`.
            if let (Some(idx), Some(r)) = (broute, &runner) {
                let saved = (ctx.new_ruri.take(), ctx.dst.take());
                ctx.new_ruri = Some(uri.clone());
                ctx.dst = Some(d);
                ctx.ext_mut::<BranchIdx>().0 = bi;
                ctx.ext.push(Box::new(InBranchRoute));
                let keep = r.run_branch(idx, ctx);
                ctx.ext.retain(|e| !e.is::<InBranchRoute>());
                let (new_uri, new_dst) = (ctx.ruri().to_vec(), ctx.dst);
                (ctx.new_ruri, ctx.dst) = saved;
                if !keep {
                    ctx.lumps.truncate(mark);
                    continue;
                }
                (d, alts) = match new_dst {
                    Some(nd) if nd != d => (nd, Vec::new()),
                    _ if new_uri != uri => self.ruri_dests(&new_uri).unwrap_or((d, Vec::new())),
                    _ => (d, alts),
                };
                uri = new_uri;
            }
            let id = self.new_branch_id(ctx.worker);
            ctx.lumps.insert(first_line_end, via_line(d.proto, ctx.advertise(d.proto), &id));
            // Record-Route/Path (rendered for this branch's transport) and
            // the contact's Path as Route set.
            let rr = sip_core::rr::branch_lines(ctx, &d);
            if !rr.is_empty() {
                ctx.lumps.insert(first_line_end, rr);
            }
            if let Some(p) = &path {
                let mut l = b"Route: ".to_vec();
                l.extend_from_slice(p);
                l.extend_from_slice(b"\r\n");
                ctx.lumps.insert(first_line_end, l);
            }
            let req_out: Arc<[u8]> = ctx.render_uri(Some(&uri)).into();
            ctx.lumps.truncate(mark);
            branches.push(Branch {
                id,
                dst: d,
                ruri: uri,
                req_out,
                group,
                state: BState::Pending,
                rt_ms: self.t1.load(Ordering::Relaxed),
                fr_inv_armed: false,
                cancel_sent: false,
                code: 0,
                reply: None,
                local: false,
                alts,
                cancel_req: None,
                cancel_rt: 0,
                ack: None,
            });
        }
        branches
    }

    /// `t_relay()` inside a failure_route: new branches on the same
    /// transaction (e.g. voicemail after busy/no answer).
    fn add_branches(&self, ctx: &mut Ctx<'_, '_>, dst: Dest, alts: Vec<Dest>) -> i32 {
        let resumed = ctx.ext::<InResume>().map(|r| r.skey.clone()).or_else(|| ctx.ext::<NewTran>().map(|n| n.skey.clone()));
        let Some(skey) = ctx.ext::<InFailure>().map(|f| f.skey.clone()).or(resumed.clone()) else { return -1 };
        let Some((base, used)) = self.txns.with(&skey, |t| (t.branches.iter().map(|b| b.group.saturating_add(1)).max().unwrap_or(0), t.used_slots())) else {
            return -1;
        };
        // Kamailio caps the whole transaction (t_fwd.c add_uac(): branch ==
        // sr_dst_max_branches → E_TOO_MANY_BRANCHES), not each relay.
        let room = sip_core::module::max_branches().saturating_sub(used);
        if room == 0 {
            ctx.branches.clear();
            return relay_error(ctx, E_TOO_MANY_BRANCHES);
        }
        let new = self.build_branches(ctx, dst, alts, base, room);
        if new.is_empty() {
            // All blocklisted: E_SEND, as in `relay`.
            return relay_error(ctx, E_SEND);
        }
        let ids: Vec<Box<[u8]>> = new.iter().map(|b| b.id.clone()).collect();
        // The first relay after t_newtran() (request route): failure_route
        // branches start from the request as it is now, unless
        // t_save_lumps() took it already (tm t_fwd.c t_forward_nonack()).
        let in_req = ctx.ext::<InFailure>().is_none() && ctx.ext::<InResume>().is_none();
        let save = match ctx.ext_get_mut::<NewTran>() {
            Some(n) if !n.saved && in_req => {
                n.saved = true;
                true
            }
            _ => false,
        };
        let saved = save.then(|| (ctx.render_uri(ctx.msg.ruri().map(<[u8]>::to_vec).as_deref()).to_vec(), ctx.ext::<sip_core::rr::RecordRoute>().cloned()));
        let arm = ctx.ext::<Arm>().map(|a| (a.failure, a.reply));
        let awaits = ctx.ext::<Arm>().is_some_and(|a| a.awaits);
        let vars = ctx.ext::<TxnVars>().cloned().unwrap_or_default();
        for id in &ids {
            self.by_branch.insert(id.clone(), skey.clone());
        }
        let mut io = Vec::new();
        let ok = self.txns.with(&skey, |t| {
            if t.final_sent || t.upstream_canceled {
                return false;
            }
            let first = t.branches.len();
            if let Some((req, rr)) = saved {
                t.fail_req = Some(req);
                if rr.is_some() {
                    t.rr = rr;
                }
            }
            t.branches.extend(new);
            t.step = first;
            // `in_failure` stays: their finals wait for the route to end (as
            // under Kamailio's reply lock), see `run_failure`.
            t.vars = vars;
            t.canceled = false; // a 6xx stopped the old branches, not the new ones
            t.on_failure = arm.and_then(|a| a.0); // re-arm explicitly for another round
            t.awaiting = awaits.then_some(None);
            t.await_ready = false;
            t.susp = None;
            if let Some(r) = arm.and_then(|a| a.1) {
                t.on_reply = Some(r);
            }
            if let Some(g) = t.branches.get(first).map(|b| b.group) {
                t.group = g;
                for i in first..t.branches.len() {
                    if t.branches.get(i).is_some_and(|b| b.group == g) {
                        t.start_branch(i, &mut io);
                    }
                }
            }
            true
        });
        if ok != Some(true) {
            for id in &ids {
                self.by_branch.remove(id);
            }
            return -1;
        }
        if let Some(f) = ctx.ext_get_mut::<InFailure>() {
            f.added = true;
        }
        if let Some(r) = ctx.ext_get_mut::<InResume>() {
            r.added = true;
        }
        let (net, worker) = (ctx.net, ctx.worker);
        self.exec(io, net, worker, &mut |d, m| drop(ctx.send(d, m)), &mut |c| self.schedule_cmd(worker, c));
        1
    }

    /// `t_relay()` and its variants (`relay`): Kamailio's `_w_t_relay_to()`.
    /// A failure in the request route after tm took the request (its
    /// `t_forward_nonack()` failed: unresolvable, nothing sent, no branch
    /// left) is answered by tm itself (`delay_error`).
    fn t_relay(self: &Arc<Self>, ctx: &mut Ctx<'_, '_>, relay: impl FnOnce(&Arc<Self>, &mut Ctx<'_, '_>) -> i32) -> i32 {
        if let Some(e) = ctx.ext_get_mut::<RelayErr>() {
            *e = RelayErr::default();
        }
        let rc = relay(self, ctx);
        if rc < 0
            && let Some(RelayErr(Some(err), trying)) = ctx.ext_get_mut::<RelayErr>().map(std::mem::take)
        {
            self.delay_error(ctx, err, trying);
        }
        rc
    }

    /// A request-route `t_relay` failed: as Kamailio's `t_relay_to()` with
    /// tm's `delayed_reply` (default 1, tm.c:236), the error reply waits for
    /// the end of the script (t_funcs.c:340-378: `set_kr(REQ_ERR_DELAYED)`,
    /// `tm_error`; tm.c:1916-1921: `FL_DELAYED_REPLY`), so the script can
    /// answer with `t_reply()` / `send_reply()` (through tm), while
    /// `sl_reply_error()` / `send_reply_error()` send nothing (the stock
    /// `if (!t_relay()) { sl_reply_error(); }` puts one reply on the wire,
    /// tm's). Then `t_unref()` sends it unless a final went out through tm
    /// (t_lookup.c:2101-2110, `kill_transaction()` t_funcs.c:161-187).
    /// An INVITE had its 100 Trying before the forwarding (t_funcs.c:330-335).
    fn delay_error(self: &Arc<Self>, ctx: &mut Ctx<'_, '_>, err: (u16, &'static str), trying: bool) {
        if ctx.ext.iter().any(|e| e.is::<InFailure>() || e.is::<InResume>()) {
            return;
        }
        let method = ctx.msg.method();
        if matches!(method, Some(Method::Ack | Method::Cancel)) {
            return;
        }
        // Another failed relay: its error is the one sent (tm_error).
        if let Some(d) = ctx.ext_get_mut::<Delayed>() {
            d.err = err;
            return;
        }
        if method == Some(Method::Invite)
            && !trying
            && ctx.ext::<NewTran>().is_none()
            && self.auto_100.load(Ordering::Relaxed)
            && let Some(t) = trying_or_reply(ctx.msg, 100, "Trying")
        {
            let up = ctx.reply_dest();
            let _ = ctx.send(&up, &t);
        }
        let done = Arc::new(AtomicBool::new(false));
        ctx.ext.push(Box::new(Delayed { err, done: done.clone() }));
        ctx.ext.push(Box::new(sip_core::module::DelayedReply));
        // t_reply() / send_reply() meanwhile: tm's final (t_reply.c
        // _reply_light(): one final only).
        let gate = done.clone();
        ctx.ext.push(Box::new(sip_core::module::TxnReply(Arc::new(move |code, _| {
            if gate.load(Ordering::Relaxed) {
                return false;
            }
            if code >= 200 {
                gate.store(true, Ordering::Relaxed);
            }
            true
        }))));
        let tm = self.clone();
        ctx.at_script_end(Box::new(move |ctx| tm.send_delayed(ctx)));
    }

    /// The end of the request route: the delayed error reply
    /// (`kill_transaction()`), through the request's transaction if it has
    /// one by now (`t_newtran`, or a later relay: its branches are
    /// canceled, as `_reply_light()` does), else as a plain reply.
    fn send_delayed(&self, ctx: &mut Ctx<'_, '_>) {
        let Some((err, done)) = ctx.ext::<Delayed>().map(|d| (d.err, d.done.load(Ordering::Relaxed))) else { return };
        if done {
            return;
        }
        let skey = ctx.ext::<NewTran>().map(|n| n.skey.clone()).or_else(|| {
            let _ = ctx.msg.parse_headers(HdrFlags::VIA);
            ctx.msg.via1.and_then(|v| txn_branch(&v)).map(|b| (b, ctx.msg.method().unwrap_or(Method::Other)))
        });
        let wait = self.wait_timer.load(Ordering::Relaxed);
        let (net, worker) = (ctx.net, ctx.worker);
        let mut io = Vec::new();
        let found = skey.and_then(|k| {
            self.txns.with(&k, |t| {
                if !t.final_sent {
                    t.cancel_all(None, net, &mut io);
                    t.local_final(err.0, err.1, wait, &mut io);
                }
            })
        });
        if found.is_none() {
            let _ = ctx.reply(err.0, err.1);
        }
        self.exec(io, net, worker, &mut |d, m| drop(ctx.send(d, m)), &mut |c| self.schedule_cmd(worker, c));
    }

    /// In a failure route, sl's `send_reply()` / `send_reply_error()` answer
    /// through tm (`TxnReply`; Kamailio sl.c:296-303, 360-364 → tm.c:1594
    /// `t_reply_str_unsafe()`): the reply is the transaction's final, so the
    /// best reply isn't relayed after the route; refused (nothing sent) when
    /// it already has one.
    fn failure_reply_gate(&self, skey: &ServerKey, worker: usize) -> Option<sip_core::module::TxnReply> {
        let me = self.me.get()?.upgrade()?;
        let key = skey.clone();
        Some(sip_core::module::TxnReply(Arc::new(move |code, r| {
            let wait = me.wait_timer.load(Ordering::Relaxed);
            let mut io = Vec::new();
            let ok = me.txns.with(&key, |t| {
                if t.final_sent {
                    return false;
                }
                if code >= 200 {
                    let r: Arc<[u8]> = r.into();
                    sip_core::stats::inc(st().rpl_generated);
                    t.final_sent = true;
                    t.in_failure = false;
                    t.local_reply_upstream(r.clone(), &mut io);
                    t.last_reply = Some(r);
                    io.push(Io::Timer(wait, TimerKind::Wait, t.timer_key()));
                }
                true
            });
            // The caller sends the reply itself.
            io.retain(|a| !matches!(a, Io::Send(..)));
            if let Some(net) = me.net().cloned() {
                me.exec(io, &*net, worker, &mut |d, m| drop(net.send(d, m)), &mut |c| me.schedule_cmd(worker, c));
            }
            ok == Some(true)
        })))
    }

    /// `t_reply(code, reason)`: stateful in a failure_route, else stateless.
    fn t_reply(&self, ctx: &mut Ctx<'_, '_>, code: u16, reason: &str) -> i32 {
        let Some(skey) = ctx
            .ext::<InFailure>()
            .map(|f| f.skey.clone())
            .or_else(|| ctx.ext::<InResume>().map(|r| r.skey.clone()))
            .or_else(|| ctx.ext::<NewTran>().map(|n| n.skey.clone()))
        else {
            // No transaction kept here; after a failed relay tm still
            // answers for the request (`TxnReply`): this is its final.
            return if matches!(ctx.send_reply(code, reason), Ok(true)) { 1 } else { -1 };
        };
        let wait = self.wait_timer.load(Ordering::Relaxed);
        let mut io = Vec::new();
        let done = self.txns.with(&skey, |t| {
            if t.final_sent {
                return false;
            }
            let Some(r) = synth(&t.orig_req, code, reason) else { return false };
            let r: Arc<[u8]> = r.into();
            t.final_sent = true;
            t.in_failure = false;
            t.local_reply_upstream(r.clone(), &mut io);
            t.last_reply = Some(r);
            io.push(Io::Timer(wait, TimerKind::Wait, t.timer_key()));
            true
        });
        if done != Some(true) {
            return -1;
        }
        if let Some(f) = ctx.ext_get_mut::<InFailure>() {
            f.replied = true;
        }
        if let Some(r) = ctx.ext_get_mut::<InResume>() {
            r.replied = true;
        }
        let (net, worker) = (ctx.net, ctx.worker);
        self.exec(io, net, worker, &mut |d, m| drop(ctx.send(d, m)), &mut |c| self.schedule_cmd(worker, c));
        1
    }

    /// Next hop from a SIP URI: `;transport=`, `sips:` → TLS, default ports,
    /// IP literals directly, host names via RFC 3263 (NAPTR/SRV/A).
    fn ruri_dest(&self, ruri: &[u8]) -> Option<Dest> {
        self.ruri_dests(ruri).map(|d| d.0)
    }

    /// Next hop plus the further DNS targets to fail over to
    /// (`use_dns_failover`).
    fn ruri_dests(&self, ruri: &[u8]) -> Option<(Dest, Vec<Dest>)> {
        let u = sip_parser::parse_uri(ruri)?;
        let given = match u.param(b"transport").map(|t| t.to_ascii_lowercase()) {
            Some(t) if t == b"tcp" => Some(if u.is_sips() { Proto::Tls } else { Proto::Tcp }),
            Some(t) if t == b"tls" => Some(Proto::Tls),
            Some(t) if t == b"ws" => Some(if u.is_sips() { Proto::Wss } else { Proto::Ws }),
            Some(t) if t == b"wss" => Some(Proto::Wss),
            Some(t) if t == b"udp" => Some(Proto::Udp),
            _ => None,
        };
        let host = std::str::from_utf8(u.host).ok()?;
        if let Ok(ip) = host.trim_matches(|c| c == '[' || c == ']').parse::<std::net::IpAddr>() {
            let proto = given.unwrap_or(if u.is_sips() { Proto::Tls } else { Proto::Udp });
            let port = u.port.unwrap_or(if proto.is_tls() { 5061 } else { 5060 });
            return Some((Dest::new(proto, SocketAddr::new(ip, port)), Vec::new()));
        }
        let key: Box<str> = format!("{given:?}:{}:{host}:{:?}", u.is_sips(), u.port).into();
        let targets = match self.dns.get_cloned(&key) {
            // With SRV load balancing the order is drawn per request (the
            // resolver still caches the records).
            Some((t, at)) if at.elapsed() < DNS_CACHE_TTL && !sip_core::dns::resolver().srv_lb.load(Ordering::Relaxed) => t,
            _ => {
                let t: Arc<[Dest]> = sip_core::dns::resolver().resolve_uri(host, u.port, given, u.is_sips()).into();
                if self.dns_bound.admit(&self.dns, |(_, at)| at.elapsed() >= DNS_CACHE_TTL) {
                    self.dns.insert(key, (t.clone(), Instant::now()));
                }
                t
            }
        };
        let (first, rest) = targets.split_first()?;
        let alts = if self.dns_failover.load(Ordering::Relaxed) { rest.to_vec() } else { Vec::new() };
        Some((*first, alts))
    }

    fn new_branch_id(&self, worker: usize) -> Box<[u8]> {
        // Formatted on the stack, then one exact-size allocation (format!
        // into a String and converting to a boxed slice allocated twice).
        const LEN: usize = 48;
        let mut buf = [0u8; LEN];
        let mut w = &mut buf[..];
        let _ = write!(w, "z9hG4bKfs.{:x}.{:x}.{:x}", branch_nonce(), worker, self.seq.fetch_add(1, Ordering::Relaxed));
        let n = LEN.saturating_sub(w.len());
        Box::from(buf.get(..n).unwrap_or_default())
    }

    /// `t_check_trans()`, as in Kamailio:
    /// - CANCEL: 1 if the INVITE it cancels has a transaction;
    /// - ACK: matches an INVITE transaction (ACK for a negative reply): it is
    ///   absorbed and the script stops (0);
    /// - other requests: a retransmission gets the last reply again and the
    ///   script stops (0);
    /// - otherwise -1.
    fn check_trans(&self, ctx: &mut Ctx<'_, '_>) -> i32 {
        if ctx.msg.parse_headers(HdrFlags::VIA).is_err() {
            return -1;
        }
        let method = ctx.msg.method().unwrap_or(Method::Other);
        let Some(branch) = ctx.msg.via1.and_then(|v| txn_branch(&v)) else { return -1 };
        let key: ServerKey = (branch, if matches!(method, Method::Ack | Method::Cancel) { Method::Invite } else { method });
        let Some(last) = self.txns.with(&key, |t| t.last_reply.clone().map(|r| (t.upstream, r))) else { return -1 };
        match method {
            Method::Cancel => 1,
            Method::Ack => 0,
            _ => {
                if let Some((up, r)) = last {
                    let _ = ctx.send(&up, &r);
                }
                0
            }
        }
    }

    /// `t_relay()` and friends: to `dst`, else `$du`, else the R-URI's next
    /// hops (over `proto` when given).
    fn forward(&self, ctx: &mut Ctx<'_, '_>, dst: Option<Dest>, proto: Option<Proto>) -> i32 {
        // A CANCEL goes where its INVITE's branches went (relay() finds the
        // transaction): its own R-URI isn't resolved.
        if ctx.msg.method() == Some(Method::Cancel) {
            let src = ctx.src;
            return self.relay(ctx, src, Vec::new());
        }
        let (mut dst, mut alts) = match dst.or(ctx.dst) {
            Some(d) => (d, Vec::new()),
            None => match self.ruri_dests(ctx.ruri()) {
                Some(d) => d,
                None => return relay_error(ctx, E_BAD_ADDRESS),
            },
        };
        if let Some(p) = proto {
            dst.proto = p;
            alts.iter_mut().for_each(|d| d.proto = p);
        }
        self.relay(ctx, dst, alts)
    }

    /// `t_lookup_request()`: 1 when the request matches a transaction (a
    /// retransmission; an ACK for a negative final of an INVITE
    /// transaction), else -1. Sends nothing, unlike `t_check_trans()`.
    fn lookup_request(&self, ctx: &mut Ctx<'_, '_>) -> i32 {
        if ctx.msg.parse_headers(HdrFlags::VIA).is_err() {
            return -1;
        }
        let method = ctx.msg.method().unwrap_or(Method::Other);
        let Some(branch) = ctx.msg.via1.and_then(|v| txn_branch(&v)) else { return -1 };
        let found = if method == Method::Ack {
            // The ACK for a 2xx is a request of its own (end to end).
            self.txns.with(&(branch, Method::Invite), |t| t.final_sent && t.last_reply.as_deref().is_some_and(|r| code_of(r) >= 300))
        } else {
            self.txns.with(&(branch, method), |_| true)
        };
        if found == Some(true) { 1 } else { -1 }
    }

    /// `t_save_lumps()`: the request with the script's edits so far (and
    /// its Record-Route) is what failure_route and `await` start from; the
    /// first relay does not take it again. Needs the transaction
    /// (`t_newtran()`, or a resumed request); -1 without one. Outside the
    /// request route, or once taken, there is nothing to do: 1.
    fn save_lumps(&self, ctx: &mut Ctx<'_, '_>) -> i32 {
        if ctx.ext::<InFailure>().is_some() {
            return 1;
        }
        if let Some(n) = ctx.ext_get_mut::<NewTran>() {
            if n.saved {
                return 1;
            }
            n.saved = true;
        }
        let Some(skey) = ctx.ext::<NewTran>().map(|n| n.skey.clone()).or_else(|| ctx.ext::<InResume>().map(|r| r.skey.clone())) else {
            return -1;
        };
        let req = ctx.render_uri(ctx.msg.ruri().map(<[u8]>::to_vec).as_deref()).to_vec();
        let rr = ctx.ext::<sip_core::rr::RecordRoute>().cloned();
        let ok = self.txns.with(&skey, |t| {
            t.fail_req = Some(req);
            if rr.is_some() {
                t.rr = rr;
            }
        });
        if ok.is_some() { 1 } else { -1 }
    }

    fn relay(&self, ctx: &mut Ctx<'_, '_>, dst: Dest, alts: Vec<Dest>) -> i32 {
        self.request_in(ctx);
        if ctx.ext.iter().any(|e| e.is::<InFailure>() || e.is::<InResume>() || e.is::<NewTran>()) {
            return self.add_branches(ctx, dst, alts);
        }
        if ctx.msg.parse_headers(HdrFlags::VIA).is_err() {
            ctx.last_error = Some((400, "Bad Via"));
            return -1;
        }
        let method = ctx.msg.method().unwrap_or(Method::Other);
        let Some(branch) = ctx.msg.via1.and_then(|v| txn_branch(&v)) else {
            ctx.last_error = Some((400, "Missing Via branch (RFC 2543 not supported)"));
            return -1;
        };
        let first_line_end = ctx.msg.first_line_end;

        match method {
            Method::Ack => {
                // ACK for a non-2xx we already ACKed hop-by-hop: absorb.
                if self.txns.with(&(branch.clone(), Method::Invite), |_| ()).is_some() {
                    return 0;
                }
                // ACK for 2xx is end-to-end: forward statelessly.
                let b = format!("z9hG4bKfs.{:x}.ack.{:x}", branch_nonce(), self.seq.fetch_add(1, Ordering::Relaxed));
                ctx.lumps.insert(first_line_end, via_line(dst.proto, ctx.advertise(dst.proto), b.as_bytes()));
                return if ctx.send_rendered(&dst).is_ok() { 1 } else { -1 };
            }
            Method::Cancel => return self.cancel(ctx, &branch),
            _ => {}
        }

        let skey: ServerKey = (branch, method);
        // Retransmission of a request we already handle?
        if let Some(last) = self.txns.with(&skey, |t| t.last_reply.clone().map(|r| (t.upstream, r))) {
            if let Some((up, r)) = last {
                let _ = ctx.send(&up, &r);
            }
            return 0;
        }

        let ovr = ctx.ext::<FrOverride>();
        let fr = ovr.and_then(|o| o.fr).unwrap_or(self.fr_timer.load(Ordering::Relaxed));
        let fr_inv = ovr.and_then(|o| o.fr_inv).unwrap_or(self.fr_inv_timer.load(Ordering::Relaxed));
        let arm = ctx.ext::<Arm>().map(|a| (a.failure, a.reply));
        let awaits = ctx.ext::<Arm>().is_some_and(|a| a.awaits);
        let branches = self.build_branches(ctx, dst, alts, 0, sip_core::module::max_branches());
        // Every next hop blocklisted: Kamailio adds the branches but sends
        // none (t_fwd.c t_send_branch()), so t_forward_nonack() fails E_SEND.
        if branches.is_empty() {
            return relay_error(ctx, E_SEND);
        }

        let cancel_hdrs = cancel_headers(ctx, method);

        let orig_req = ctx.msg.buf.to_vec();
        // Only kept when a failure route or `await` may start new branches.
        let (fail_req, rr) = if arm.is_some_and(|a| a.0.is_some()) || awaits {
            let req = (!ctx.lumps.is_empty()).then(|| ctx.render_uri(ctx.msg.ruri().map(<[u8]>::to_vec).as_deref()).to_vec());
            (req, ctx.ext::<sip_core::rr::RecordRoute>().cloned())
        } else {
            (None, None)
        };
        // INVITE: answer 100 Trying at once (stops upstream retransmissions).
        // From the request as received (already parsed), not a re-parse of the copy.
        let trying: Option<Arc<[u8]>> =
            (method == Method::Invite && self.auto_100.load(Ordering::Relaxed)).then(|| trying_or_reply(ctx.msg, 100, "Trying")).flatten().map(Into::into);
        let ids: Vec<Box<[u8]>> = branches.iter().map(|b| b.id.clone()).collect();
        // The first group goes out right after publishing. Marked Calling here,
        // before the transaction is visible (no reply can precede our send),
        // which saves taking its lock again just for this.
        let mut branches = branches;
        let first: Vec<FirstSend> = branches
            .iter_mut()
            .enumerate()
            .filter(|(_, b)| b.group == 0)
            .map(|(i, b)| {
                b.state = BState::Calling;
                (i, b.dst, b.req_out.clone(), b.id.clone())
            })
            .collect();
        let txn = Txn {
            method,
            created: Instant::now(),
            timed: 0,
            upstream: ctx.reply_dest(),
            orig_req,
            fail_req,
            rr,
            cancel_hdrs,
            branches,
            group: 0,
            canceled: false,
            final_sent: false,
            last_reply: trying.clone(),
            fr,
            fr_inv,
            skey: skey.clone(),
            on_failure: arm.and_then(|a| a.0),
            on_reply: arm.and_then(|a| a.1),
            awaiting: awaits.then_some(None),
            await_ready: false,
            in_failure: false,
            upstream_canceled: false,
            vars: ctx.ext::<TxnVars>().cloned().unwrap_or_default(),
            local: false,
            local_cb: None,
            susp: None,
            timer_id: None,
            handle: 0,
            t1: self.t1.load(Ordering::Relaxed),
            t2: self.t2.load(Ordering::Relaxed),
            blind: 0,
            step: 0,
            max_br: sip_core::module::max_branches(),
        };
        // Publish before sending: a reply may be processed by another thread
        // (another UDP worker, or a TCP reader) before send() returns.
        if !self.txns.insert_if_absent(skey.clone(), txn) {
            return 0; // a concurrent retransmission won the race
        }
        sip_core::stats::inc(st().total);
        for id in &ids {
            self.by_branch.insert(id.clone(), skey.clone());
        }
        if let Some(t) = &trying {
            let up = ctx.reply_dest();
            let _ = ctx.send(&up, t);
        }

        // Start the first group; synchronous send failures become local 477s.
        let wait = self.wait_timer.load(Ordering::Relaxed);
        let net = ctx.net;
        let mut io = Vec::new();
        let mut failed = Vec::new();
        for (i, d, m, id) in &first {
            if let Err(e) = ctx.send(d, m) {
                sip_core::log::log(sip_core::log::L_WARN, &format!("tm: send to {d}: {e}"));
                failed.push(*i);
            } else {
                if d.proto == Proto::Udp {
                    io.push(Io::Timer(self.t1.load(Ordering::Relaxed), TimerKind::Retransmit, id.clone()));
                }
                io.push(Io::Timer(fr, TimerKind::FinalResponse, id.clone()));
            }
        }
        // Nothing could be sent and nothing else to try: let the script
        // decide (it usually answers with sl_reply_error()). Claimed under
        // the transaction lock: a reader thread may already have seen the
        // connection fail and answered 477 through on_transport_event (a
        // refused loopback connect can fail before our own write returns).
        // Then the request has its final reply and the script must not send
        // another one.
        let all_failed = failed.len() == first.len()
            && self.txns.with(&skey, |t| {
                let claim = t.branches.len() == first.len() && !t.final_sent;
                if claim {
                    t.final_sent = true;
                    t.branches.iter_mut().for_each(|b| b.state = BState::Completed);
                }
                claim
            }) == Some(true);
        if all_failed {
            self.drop_txn(&skey);
            if trying.is_some() {
                ctx.ext_mut::<RelayErr>().1 = true;
            }
            return relay_error(ctx, E_SEND);
        }
        if !failed.is_empty() {
            self.txns.with(&skey, |t| {
                for &i in &failed {
                    t.on_local_final(i, E_SEND.0, E_SEND.1, wait, net, &mut io);
                }
            });
        }
        let worker = ctx.worker;
        self.exec(io, ctx.net, worker, &mut |d, m| drop(ctx.send(d, m)), &mut |c| self.schedule_cmd(worker, c));
        1
    }

    fn cancel(&self, ctx: &mut Ctx<'_, '_>, branch: &[u8]) -> i32 {
        let ikey: ServerKey = (branch.into(), Method::Invite);
        let net = ctx.net;
        let mut io = Vec::new();
        let wait = self.wait_timer.load(Ordering::Relaxed);
        let found = self.txns.with(&ikey, |t| {
            t.upstream_canceled = true;
            if !t.final_sent {
                t.cancel_all(None, net, &mut io);
                // Suspended (no branch to answer): the INVITE gets its 487 now.
                if t.branches.is_empty() {
                    t.susp = None;
                    t.local_final(487, "Request Terminated", wait, &mut io);
                }
            }
        });
        if found.is_none() {
            let _ = ctx.reply(481, "Call/Transaction Does Not Exist");
            return 0;
        }
        let _ = ctx.reply(200, "OK");
        let worker = ctx.worker;
        self.exec(io, ctx.net, worker, &mut |d, m| drop(ctx.send(d, m)), &mut |c| self.schedule_cmd(worker, c));
        0
    }

    fn drop_txn(&self, skey: &ServerKey) {
        if let Some(t) = self.txns.remove(skey) {
            for b in &t.branches {
                self.by_branch.remove(&b.id);
            }
            if let Some(id) = &t.timer_id {
                self.by_branch.remove(id);
            }
            if t.handle != 0 {
                self.handles.remove(&t.handle);
            }
        }
    }

    /// Hop-by-hop ACK for a non-2xx final reply to our INVITE.
    fn send_ack(&self, ctx: &mut Ctx<'_, '_>, id: &[u8], ruri: &[u8], dst: Dest) -> Option<Arc<[u8]>> {
        let adv = ctx.advertise(dst.proto);
        let m = &mut *ctx.msg;
        if m.parse_headers(HdrFlags::EOH).is_err() {
            return None;
        }
        let mut a = Vec::with_capacity(512);
        a.extend_from_slice(b"ACK ");
        a.extend_from_slice(ruri);
        a.extend_from_slice(b" SIP/2.0\r\n");
        a.extend_from_slice(&via_line(dst.proto, adv, id));
        for h in m.headers.iter() {
            match h.kind {
                HdrKind::From | HdrKind::To | HdrKind::CallId => a.extend_from_slice(m.buf.get(h.start..h.end).unwrap_or_default()),
                HdrKind::CSeq => {
                    let n = h.body.split(|c| c.is_ascii_whitespace()).next().unwrap_or(b"1");
                    a.extend_from_slice(b"CSeq: ");
                    a.extend_from_slice(n);
                    a.extend_from_slice(b" ACK\r\n");
                }
                _ => {}
            }
        }
        a.extend_from_slice(b"Max-Forwards: 70\r\nContent-Length: 0\r\n\r\n");
        let _ = ctx.send(&dst, &a);
        Some(a.into())
    }

    fn handle_reply(&self, ctx: &mut Ctx<'_, '_>) -> bool {
        if ctx.msg.parse_headers(HdrFlags::VIA).is_err() {
            return false;
        }
        let Some(code) = ctx.msg.status() else { return false };
        sip_core::stats::inc(st().rpl_received);
        let Some(via) = ctx.msg.via1 else { return false };
        let Some(branch) = via.branch else { return false };
        let Some(skey) = self.by_branch.get_cloned(branch) else { return false }; // not ours
        let id: Box<[u8]> = branch.into();
        // A reply to our CANCEL shares the INVITE branch's Via: it ends the
        // CANCEL's retransmissions and goes no further.
        let cseq_cancel = skey.1 == Method::Invite
            && ctx.msg.parse_headers(HdrFlags::CSEQ).is_ok()
            && ctx
                .msg
                .get(HdrKind::CSeq)
                .is_some_and(|h| h.body.split(|c| c.is_ascii_whitespace()).filter(|x| !x.is_empty()).nth(1).is_some_and(|m| m.eq_ignore_ascii_case(b"CANCEL")));
        if cseq_cancel {
            if code >= 200 {
                self.txns.with(&skey, |t| {
                    if let Some(b) = t.branches.iter_mut().find(|b| b.id == id) {
                        b.cancel_rt = 0;
                    }
                });
            }
            return true;
        }
        // onreply_route[name] armed with t_on_reply(): may edit the reply
        // (lumps) or `drop` a provisional.
        let route = self.txns.with(&skey, |t| t.on_reply.map(|r| (r, t.vars.clone(), t.branches.iter().position(|b| b.id == id)))).flatten();
        if let (Some((idx, vars, bi)), Some(runner)) = (route, self.hub.get().and_then(|h| h.runner())) {
            *ctx.ext_mut::<TxnVars>() = vars;
            ctx.ext_mut::<BranchIdx>().0 = bi.unwrap_or(0);
            let keep = runner.run_onreply(idx, ctx);
            let vars = ctx.ext::<TxnVars>().cloned().unwrap_or_default();
            self.txns.with(&skey, |t| t.vars = vars);
            if !keep && code < 200 {
                return true;
            }
        }

        // Strip our Via: whole line, or just the first value if the line has more.
        // via1 is parsed, so via1_hdr is set; never relay a reply with our Via.
        let Some(hdr) = ctx.msg.via1_hdr.and_then(|i| ctx.msg.headers.get(i)).copied() else {
            sip_core::log::log(sip_core::log::L_BUG, "tm: reply without its first Via header, dropped");
            return true;
        };
        match ctx.msg.via1_next {
            Some(next) => {
                let at = ctx.msg.offset_of(via.raw);
                ctx.lumps.delete(at, next.saturating_sub(at));
            }
            None => ctx.lumps.delete(hdr.start, hdr.end.saturating_sub(hdr.start)),
        }
        // One copy of the reply as it goes upstream, shared by the send
        // queue, the branch and last_reply.
        let fwd: Arc<[u8]> = ctx.render().into();

        let wait = self.wait_timer.load(Ordering::Relaxed);
        let net = ctx.net;
        let mut io = Vec::new();
        let mut ack = None;
        self.txns.with(&skey, |t| {
            let Some((i, b)) = t.branches.iter_mut().enumerate().find(|(_, b)| b.id == id) else { return };
            let st = b.state;
            if code < 200 {
                if st == BState::Calling {
                    b.state = BState::Proceeding;
                    if t.method == Method::Invite && !b.fr_inv_armed {
                        // From now on fr_inv_timer decides, counted from this 1xx.
                        b.fr_inv_armed = true;
                        io.push(Io::Timer(t.fr_inv, TimerKind::InviteFinal, b.id.clone()));
                    }
                }
                if t.canceled && t.method == Method::Invite && !b.cancel_sent && b.state == BState::Proceeding {
                    // §9.1: a CANCEL waits for the branch's first provisional.
                    t.send_cancel(i, net, &mut io);
                }
                if code > 100 && !t.final_sent && st != BState::Completed {
                    t.reply_upstream(fwd.clone(), false, &mut io);
                    t.last_reply = Some(fwd.clone());
                }
                return;
            }
            if t.method == Method::Invite && code >= 300 {
                ack = Some((b.ruri.clone(), b.dst, b.ack.clone()));
            }
            if st == BState::Completed {
                // Retransmitted final: 2xx to INVITE are end-to-end, pass on.
                if t.method == Method::Invite && (200..300).contains(&code) {
                    t.reply_upstream(fwd.clone(), false, &mut io);
                }
                return;
            }
            t.on_final(i, code, fwd.clone(), wait, net, &mut io);
        });
        match ack {
            // Retransmitted final: the same ACK again.
            Some((_, dst, Some(a))) => drop(ctx.send(&dst, &a)),
            Some((ruri, dst, None)) => {
                if let Some(a) = self.send_ack(ctx, &id, &ruri, dst) {
                    self.txns.with(&skey, |t| {
                        if let Some(b) = t.branches.iter_mut().find(|b| b.id == id) {
                            b.ack = Some(a);
                        }
                    });
                }
            }
            None => {}
        }
        let worker = ctx.worker;
        self.exec(io, ctx.net, worker, &mut |d, m| drop(ctx.send(d, m)), &mut |c| self.schedule_cmd(worker, c));
        true
    }

    /// A timer fired for branch `cmd.branch`; returns follow-up side effects.
    fn on_timer(&self, cmd: &TimerCmd, net: &dyn Outbound, io: &mut Vec<Io>) {
        let Some(skey) = self.by_branch.get_cloned(&cmd.branch) else { return };
        if let TimerKind::Wait = cmd.kind {
            self.drop_txn(&skey);
            return;
        }
        let wait = self.wait_timer.load(Ordering::Relaxed);
        self.txns.with(&skey, |t| {
            if t.timer_id.as_deref() == Some(&*cmd.branch) {
                // Suspended too long (nobody resumed it, or the resumed
                // script neither relayed nor replied).
                if t.branches.is_empty() && !t.final_sent {
                    t.susp = None;
                    t.local_final(500, "Server Internal Error - Suspended Too Long", wait, io);
                }
                return;
            }
            let Some(i) = t.branches.iter().position(|b| b.id == cmd.branch) else { return };
            let invite = t.method == Method::Invite;
            match cmd.kind {
                TimerKind::Retransmit => {
                    let Some(b) = t.branches.get_mut(i) else { return };
                    let active = if invite { b.state == BState::Calling } else { matches!(b.state, BState::Calling | BState::Proceeding) };
                    if active {
                        sip_core::stats::inc(st().retransmissions);
                        io.push(send_io(b.dst, b.req_out.clone()));
                        b.rt_ms = if invite { b.rt_ms.saturating_mul(2) } else { b.rt_ms.saturating_mul(2).min(t.t2) };
                        io.push(Io::Timer(b.rt_ms, TimerKind::Retransmit, b.id.clone()));
                    }
                }
                TimerKind::FinalResponse | TimerKind::InviteFinal => {
                    let (fr, fr_inv) = (t.fr, t.fr_inv);
                    let Some(b) = t.branches.get_mut(i) else { return };
                    let inv_timer = matches!(cmd.kind, TimerKind::InviteFinal);
                    match b.state {
                        BState::Completed | BState::Pending => {}
                        // A ringing INVITE: its own fr_inv_timer (started by
                        // the 1xx) decides, not fr_timer.
                        BState::Proceeding if invite && b.fr_inv_armed && !inv_timer => {}
                        // Ringing without a timer of its own (a 1xx seen
                        // before the branch was Calling): fr_inv from now.
                        BState::Proceeding if invite && !b.fr_inv_armed && fr_inv > fr => {
                            b.fr_inv_armed = true;
                            io.push(Io::Timer(fr_inv.saturating_sub(fr), TimerKind::InviteFinal, b.id.clone()));
                        }
                        state => {
                            // No final in time: CANCEL a ringing INVITE branch and
                            // treat the branch as a local 408.
                            if invite && state == BState::Proceeding && !b.cancel_sent {
                                t.send_cancel(i, net, io);
                            }
                            sip_core::stats::inc(st().timeouts);
                            t.on_local_final(i, 408, "Request Timeout", wait, net, io);
                        }
                    }
                }
                TimerKind::CancelRetransmit => {
                    let t2 = t.t2;
                    let Some(b) = t.branches.get_mut(i) else { return };
                    // Until the CANCEL is answered, or the INVITE got a real final.
                    let answered = b.state == BState::Completed && !b.local && b.code != 0;
                    if b.cancel_rt > 0 && !answered {
                        if let Some(m) = &b.cancel_req {
                            io.push(Io::Send(b.dst, m.clone()));
                        }
                        b.cancel_rt = b.cancel_rt.saturating_mul(2).min(t2);
                        io.push(Io::Timer(b.cancel_rt, TimerKind::CancelRetransmit, b.id.clone()));
                    }
                }
                TimerKind::CancelTimeout => {
                    let Some(b) = t.branches.get_mut(i) else { return };
                    b.cancel_rt = 0;
                    if b.state != BState::Completed {
                        sip_core::stats::inc(st().timeouts);
                        t.on_local_final(i, 408, "Request Timeout", wait, net, io);
                    }
                }
                TimerKind::Wait => {}
            }
        });
    }

    fn timer_loop(&self, net: Arc<dyn Outbound>) {
        let mut wheel: TimerWheel<TimerCmd> = TimerWheel::new(8192);
        let start = Instant::now();
        let mut fired = Vec::new();
        let mut batch = Vec::new();
        loop {
            let next_tick = tick_deadline(start, wheel.now().saturating_add(1));
            if let Some(d) = next_tick.checked_duration_since(Instant::now()) {
                thread::sleep(d);
            }
            for ib in self.inbox.iter() {
                // Swap the vector out so the lock is held for O(1).
                std::mem::swap(&mut *lock(ib), &mut batch);
                for c in batch.drain(..) {
                    wheel.schedule(ms_to_ticks(c.delay_ms), c);
                }
            }
            wheel.advance(&mut fired);
            for cmd in fired.drain(..) {
                // One timer's bug must not stop every other transaction's
                // timers (the thread would die and nothing would time out).
                let r = sip_core::panic::catch(|| {
                    let mut io = Vec::new();
                    self.on_timer(&cmd, &*net, &mut io);
                    self.exec(io, &*net, 0, &mut |d, m| drop(net.send(d, m)), &mut |c| wheel.schedule(ms_to_ticks(c.delay_ms), c));
                });
                if r.is_err() {
                    sip_core::elog!("tm: panic in a {:?} timer; that timer is dropped", cmd.kind);
                }
            }
        }
    }
}

/// Headers for CANCELs (§9.1: same From, To, Call-ID, CSeq number, Route).
/// Only INVITEs can be canceled, so only they pay for the full header parse.
/// Kamailio t_reply.c t_should_relay_response(), after the failure route:
/// which replies of the `branches` that existed before it stop competing
/// for the final (`reply` cleared, as Kamailio clears `uac[i].reply`).
/// `mode` is `failure_reply_mode` or what `t_drop_replies` set:
/// 0 keep all; 1 drop all; 2 drop those of the last relay (from `step`, its
/// first branch); 3 drop all, but only when the route `added` branches.
/// True when replies were dropped.
fn drop_replies(branches: &mut [Branch], step: usize, mode: u8, added: bool) -> bool {
    let drop = match mode {
        0 => false,
        3 => added,
        _ => true,
    };
    if drop {
        let from = if mode == 2 && step < branches.len() { step } else { 0 };
        for b in branches.iter_mut().skip(from) {
            b.reply = None;
        }
    }
    drop
}

/// A relay failed: the error for `sl_reply_error()` / `send_reply_error()`,
/// and in a failure route also Kamailio's `tm_error` (the reply if the route
/// dropped the replies and added no branch). -1.
fn relay_error(ctx: &mut Ctx<'_, '_>, err: (u16, &'static str)) -> i32 {
    ctx.last_error = Some(err);
    match ctx.ext_get_mut::<InFailure>() {
        Some(f) => f.tm_error = Some(err),
        None => ctx.ext_mut::<RelayErr>().0 = Some(err),
    }
    -1
}

fn cancel_headers(ctx: &mut Ctx<'_, '_>, method: Method) -> Vec<u8> {
    if method != Method::Invite {
        return Vec::new();
    }
    let mut cancel_hdrs = Vec::with_capacity(256);
    let _ = ctx.msg.parse_headers(HdrFlags::EOH);
    for h in ctx.msg.headers.iter() {
        match h.kind {
            HdrKind::From | HdrKind::To | HdrKind::CallId | HdrKind::Route => {
                cancel_hdrs.extend_from_slice(ctx.msg.buf.get(h.start..h.end).unwrap_or_default())
            }
            HdrKind::CSeq => {
                let n = h.body.split(|c| c.is_ascii_whitespace()).next().unwrap_or(b"1");
                cancel_hdrs.extend_from_slice(b"CSeq: ");
                cancel_hdrs.extend_from_slice(n);
                cancel_hdrs.extend_from_slice(b" CANCEL\r\n");
            }
            _ => {}
        }
    }
    cancel_hdrs
}

/// CANCEL headers of a request we built ourselves (`t_uac` INVITE).
fn local_cancel_headers(m: &[u8]) -> Vec<u8> {
    let head = m.split(|&c| c == b'\n').take_while(|l| l.len() > 1);
    let mut v = Vec::with_capacity(256);
    for l in head.skip(1) {
        let mut parts = l.splitn(2, |&c| c == b':');
        let name = parts.next().unwrap_or_default().trim_ascii();
        if [&b"From"[..], b"To", b"Call-ID", b"Route"].iter().any(|h| name.eq_ignore_ascii_case(h)) {
            v.extend_from_slice(l);
            v.push(b'\n');
        } else if name.eq_ignore_ascii_case(b"CSeq") {
            let body = parts.next().unwrap_or_default();
            let n = body.split(|c| c.is_ascii_whitespace()).find(|x| !x.is_empty()).unwrap_or(b"1");
            v.extend_from_slice(b"CSeq: ");
            v.extend_from_slice(n);
            v.extend_from_slice(b" CANCEL\r\n");
        }
    }
    v
}

/// `proto:addr[#conn]` (how contacts keep their next hop in an XAVP).
fn dest_to_str(d: &Dest) -> String {
    d.to_string()
}

fn dest_from_str(s: &str) -> Option<Dest> {
    let (d, conn) = match s.split_once('#') {
        Some((d, c)) => (d, c.parse().ok()),
        None => (s, None),
    };
    let mut d = Dest::parse(d).ok()?;
    d.conn = conn;
    Some(d)
}

/// A contact for serial forking (R-URI or destination-set entry).
type Contact = sip_core::module::Branch;

type Item = std::collections::HashMap<String, Val>;

fn to_item(c: &Contact) -> Item {
    let mut m = Item::new();
    m.insert("uri".to_string(), Val::str(&c.uri));
    if let Some(q) = c.q {
        m.insert("q".to_string(), Val::Int(i64::from(q)));
    }
    if let Some(d) = c.dst {
        m.insert("dst_uri".to_string(), Val::Str(dest_to_str(&d)));
    }
    if let Some(p) = &c.path {
        m.insert("path".to_string(), Val::str(p));
    }
    if let Some(i) = &c.instance {
        m.insert("instance".to_string(), Val::str(i));
    }
    if let Some(r) = c.reg_id {
        m.insert("reg_id".to_string(), Val::Int(i64::from(r)));
    }
    m
}

fn from_item(m: &Item) -> Option<Contact> {
    let text = |k: &str| match m.get(k) {
        Some(Val::Str(s)) => Some(s.clone()),
        _ => None,
    };
    Some(Contact {
        uri: text("uri")?.into_bytes(),
        dst: text("dst_uri").and_then(|d| dest_from_str(&d)),
        q: match m.get("q") {
            Some(Val::Int(q)) => u16::try_from(*q).ok(),
            _ => None,
        },
        path: text("path").map(String::into_bytes),
        instance: text("instance").map(String::into_bytes),
        reg_id: match m.get("reg_id") {
            Some(Val::Int(r)) => u32::try_from(*r).ok(),
            _ => None,
        },
    })
}

/// Make `c` the R-URI target (`$ru`, `$du`, Path, flow).
fn set_ruri(ctx: &mut Ctx<'_, '_>, c: Contact) {
    ctx.ext.retain(|e| !e.is::<sip_core::module::RuriPath>() && !e.is::<sip_core::module::RuriFlow>());
    ctx.new_ruri = Some(c.uri);
    ctx.dst = c.dst;
    ctx.ruri_q = c.q;
    if let Some(p) = c.path {
        ctx.ext.push(Box::new(sip_core::module::RuriPath(p)));
    }
    ctx.ext.push(Box::new(sip_core::module::RuriFlow { instance: c.instance, reg_id: c.reg_id }));
}

/// `t_load_contacts()` modes (Kamailio's).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum LoadMode {
    /// Highest q first; equal q are forked in parallel.
    Standard,
    /// One contact at a time, in a random order weighted by q; contacts
    /// with q = 0 or none come last, one at a time.
    Proportional,
}

/// Nanoseconds since the epoch modulo 2^64 (the low bits of
/// `as_nanos()`): seed material only.
fn clock_seed() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| d.as_secs().wrapping_mul(1_000_000_000).wrapping_add(u64::from(d.subsec_nanos())))
}

/// Uniform in `0..n` (`n` > 0): xorshift, per thread.
fn rand_below(n: u64) -> u64 {
    thread_local! {
        static S: std::cell::Cell<u64> = std::cell::Cell::new({
            sip_core::fx_hash(&(clock_seed() ^ u64::from(branch_nonce())).to_le_bytes()) | 1
        });
    }
    S.with(|s| {
        let mut x = s.get();
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        s.set(x);
        x.checked_rem(n).unwrap_or(0)
    })
}

/// A contact's q for `t_load_contacts()`: none is Kamailio's
/// Q_UNSPECIFIED (-1), below every given q.
fn load_q(c: &Contact) -> i32 {
    c.q.map_or(-1, i32::from)
}

/// Proportional order (tm t_serial.c): draw the contacts with q > 0 with
/// probability q / (sum of the q left); then the others (q = 0 or none)
/// in their order. Every contact is tried on its own.
fn proportional(mut all: Vec<Contact>, draw: &mut impl FnMut(u64) -> u64) -> Vec<Contact> {
    let q = |c: &Contact| u64::try_from(load_q(c)).unwrap_or(0);
    let backup: Vec<Contact> = all.iter().filter(|c| q(c) == 0).cloned().collect();
    all.retain(|c| q(c) > 0);
    let mut out = Vec::with_capacity(all.len().saturating_add(backup.len()));
    while !all.is_empty() {
        // q is at most 1000: the sum doesn't overflow.
        let mut n = draw(all.iter().map(q).sum());
        let i = all.iter().position(|c| match n.checked_sub(q(c)) {
            None => true, // n < q(c): this one
            Some(rest) => {
                n = rest;
                false
            }
        });
        out.push(all.remove(i.unwrap_or(0)));
    }
    out.extend(backup);
    out
}

/// `t_load_contacts([mode])` (tm t_serial.c): R-URI + destination set
/// into the contacts XAVP, in the order they are tried, each item's
/// `q_flag` 1 where its group (forked in parallel) ends; the destination
/// set is cleared. A contact without q counts as -1 (Kamailio's
/// Q_UNSPECIFIED). Standard mode: highest q first, equal q in one group.
/// Proportional mode: the contacts with q > 0 one at a time in a random
/// order weighted by q, then the rest one at a time. Of several flows (RFC
/// 5626 reg-ids) of one `+sip.instance` only the first is a contact; the
/// others wait in the flows XAVP for `t_next_contact_flow()`. Does nothing
/// when there is a single target and no extra flows.
fn load_contacts(ctx: &mut Ctx<'_, '_>, avp: &str, flows_avp: &str, mode: LoadMode) -> i32 {
    let mut all: Vec<Contact> = Vec::new();
    let path = ctx.ext::<sip_core::module::RuriPath>().map(|p| p.0.clone()).filter(|p| !p.is_empty());
    let flow = ctx.ext::<sip_core::module::RuriFlow>().cloned().unwrap_or_default();
    all.push(Contact { uri: ctx.ruri().to_vec(), dst: ctx.dst, q: ctx.ruri_q, path, instance: flow.instance, reg_id: flow.reg_id });
    all.extend(ctx.branches.iter().cloned());
    let mut flows = Vec::new();
    let mut seen: Vec<Vec<u8>> = Vec::new();
    all.retain(|c| match (&c.instance, c.reg_id) {
        (Some(i), Some(r)) if r > 0 => {
            if seen.contains(i) {
                flows.push(c.clone());
                false
            } else {
                seen.push(i.clone());
                true
            }
        }
        _ => true,
    });
    if flows.is_empty() && all.len() < 2 {
        return 1;
    }
    let items = match mode {
        LoadMode::Standard => {
            all.sort_by_key(|c| std::cmp::Reverse(load_q(c))); // stable: equal q keep their order
            // Each with the next one (none after the last).
            let nexts = all.iter().skip(1).map(Some).chain([None]);
            all.iter().zip(nexts).map(|(c, next)| item(c, next.is_none_or(|nx| load_q(nx) != load_q(c)))).collect()
        }
        LoadMode::Proportional => proportional(all, &mut rand_below).iter().map(|c| item(c, true)).collect(),
    };
    let vars = ctx.ext_mut::<TxnVars>();
    vars.xavps.insert(avp.to_string(), items);
    if flows.is_empty() {
        vars.xavps.remove(flows_avp);
    } else {
        vars.xavps.insert(flows_avp.to_string(), flows.iter().map(to_item).collect());
    }
    ctx.branches.clear();
    1
}

/// A contacts XAVP item; `q_flag` 1 ends a group of parallel branches.
fn item(c: &Contact, last: bool) -> Item {
    let mut m = to_item(c);
    m.insert("q_flag".to_string(), Val::Int(last.into()));
    m
}

/// `t_next_contacts()`: the next group of the contacts XAVP (up to the
/// item marked `last`; without marks, the items of the highest q) becomes
/// the R-URI + destination set. 1 = loaded, -2 = nothing left.
fn next_contacts(ctx: &mut Ctx<'_, '_>, avp: &str) -> i32 {
    let Some(items) = ctx.ext_get_mut::<TxnVars>().and_then(|v| v.xavps.get_mut(avp)) else { return -2 };
    if items.is_empty() {
        return -2;
    }
    let q = |m: &Item| match m.get("q") {
        Some(Val::Int(q)) => *q,
        _ => 1000,
    };
    let n = match items.iter().position(|m| matches!(m.get("q_flag"), Some(Val::Int(l)) if *l != 0)) {
        Some(i) => i.saturating_add(1),
        None if items.iter().any(|m| m.contains_key("q_flag")) => items.len(),
        None => {
            let top = items.first().map(q);
            items.iter().take_while(|m| Some(q(m)) == top).count()
        }
    };
    let group: Vec<_> = items.drain(..n).collect();
    if items.is_empty() {
        ctx.ext_mut::<TxnVars>().xavps.remove(avp);
    }
    ctx.branches.clear();
    for (i, c) in group.iter().filter_map(from_item).enumerate() {
        if i == 0 {
            set_ruri(ctx, c);
        } else {
            ctx.branches.push(c);
        }
    }
    1
}

/// `t_next_contact_flow()` (failure_route): the next flow (another reg-id
/// of a `+sip.instance`) becomes the R-URI. 1 = loaded, -1 = none left.
fn next_contact_flow(ctx: &mut Ctx<'_, '_>, flows_avp: &str) -> i32 {
    let Some(items) = ctx.ext_get_mut::<TxnVars>().and_then(|v| v.xavps.get_mut(flows_avp)) else { return -1 };
    if items.is_empty() {
        return -1;
    }
    let item = items.remove(0);
    let Some(c) = from_item(&item) else { return -1 };
    ctx.branches.clear();
    set_ruri(ctx, c);
    1
}

