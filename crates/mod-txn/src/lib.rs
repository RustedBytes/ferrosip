    #[test]
    fn proportional_order() {
        let c = |u: &str, q: Option<u16>| Contact { uri: u.as_bytes().to_vec(), q, ..Default::default() };
        let all = vec![c("a", Some(0)), c("b", Some(300)), c("c", Some(700)), c("d", None)];
        // Draws: 400 of 1000 → c (b covers 0..300); then 0 of 300 → b; then
        // the backups (q 0, and none: Kamailio's -1) in their order.
        let mut draws = vec![400u64, 0].into_iter();
        let mut totals = Vec::new();
        let out = proportional(all.clone(), &mut |n| {
            totals.push(n);
            draws.next().unwrap()
        });
        let uris: Vec<_> = out.iter().map(|c| String::from_utf8_lossy(&c.uri).into_owned()).collect();
        assert_eq!((uris, totals), (vec!["c".into(), "b".into(), "a".into(), "d".into()], vec![1000, 300]));
        // Weighted: c (q 0.7) first about 70% of the time.
        let first_c = (0..2000).filter(|_| proportional(all.clone(), &mut rand_below)[0].uri == b"c").count();
        assert!((1200..1600).contains(&first_c), "{first_c}");
    }

