    /// failure_reply_mode / t_drop_replies (Kamailio t_reply.c
    /// t_should_relay_response()): which replies of the branches before the
    /// failure route stay candidates. Branches 0 and 1 were the first
    /// relay, 2 and 3 the second (step 2).
    #[test]
    fn failure_reply_modes() {
        let kept = |mode: u8, added: bool| {
            let mut b: Vec<Branch> = [486, 404, 503, 480].into_iter().map(branch).collect();
            let dropped = drop_replies(&mut b, 2, mode, added);
            (dropped, b.iter().map(|b| b.reply.is_some()).collect::<Vec<_>>())
        };
        for added in [false, true] {
            assert_eq!(kept(0, added), (false, vec![true; 4]));
            assert_eq!(kept(1, added), (true, vec![false; 4]));
            assert_eq!(kept(2, added), (true, vec![true, true, false, false]));
        }
        assert_eq!(kept(3, false), (false, vec![true; 4]));
        assert_eq!(kept(3, true), (true, vec![false; 4]));
        // Mode 2 without a step mark inside: from the first branch.
        let mut b: Vec<Branch> = [486, 404].into_iter().map(branch).collect();
        assert!(drop_replies(&mut b, 5, 2, false) && b.iter().all(|b| b.reply.is_none()));
    }

