//! tm — stateful transaction module with forking (RFC 3261 §16, §17).
//!
//! * `t_relay()` creates one transaction per request with one client branch
//!   per target: the R-URI (`$ru`/`$du`) plus every branch in the
//!   destination set (`append_branch()`, or `lookup()` for all contacts of a
//!   user). Branches are sent in parallel, or with `fork_by_q` in groups of
//!   descending q-value (serial forking, RFC 3261 §16.6 step 1 / §16.7).
//! * Responses are aggregated per §16.7: 1xx (except 100) and every 2xx are
//!   forwarded at once; the first 2xx or a 6xx to an INVITE CANCELs the other
//!   branches; otherwise, once all branches are final, the best response is
//!   chosen (6xx, else the lowest class, preferring 401/407/415/420/484 in
//!   4xx), 503 becomes 500, and the challenges of all 401/407 branches are
//!   merged into the one sent upstream.
//! * INVITEs get an immediate `100 Trying`. Upstream CANCELs fan out to every
//!   branch (to branches still waiting for a provisional, as soon as one
//!   arrives, per §9.1). Non-2xx finals are ACKed hop-by-hop per branch.
//! * Timers (one thread, timer wheel, fed via per-worker inboxes — workers
//!   never wake it): UDP retransmission (T1 doubling, capped at T2 for
//!   non-INVITE), `fr_timer` (no provisional) and `fr_inv_timer` (ringing)
//!   per branch — on expiry the branch gets a local 408 (and a CANCEL if it
//!   was ringing) — and the wait timer that keeps a completed transaction to
//!   absorb retransmissions. `t_set_fr(fr_inv, fr)` overrides per transaction.
//! * Outbound connections that never come up fail their branches with 477.
//!
//! All state of a transaction lives under one shard lock; actions (sends,
//! timers) are collected under the lock and executed after releasing it.

