//! RFC 3263 §4.3 failover of the initial INVITE across the resolved targets.
//!
//! The driver resolves the next hop into an ordered list. The INVITE goes
//! to the first target; it moves to the next one (new transaction: new
//! branch and CSeq, same Call-ID and From tag) on a transport error, a
//! transaction timeout, a 503 before any provisional other than 100, or —
//! when more targets remain — no response at all within
//! `failover_timeout_ms`.

use super::*;

#[derive(Debug, Default)]
#[cfg_attr(feature = "recovery", derive(serde::Serialize, serde::Deserialize))]
pub(super) struct Failover {
    /// Targets not tried yet, in order.
    #[cfg_attr(feature = "recovery", serde(with = "crate::recovery::dest_serde::vec"))]
    pub(super) alternatives: Vec<Dest>,
    /// Any response to the current INVITE (stops the no-response probe).
    pub(super) responded: bool,
    /// A provisional other than 100, or a final: a UAS was reached.
    pub(super) reached: bool,
    /// The Contact was generated by the engine (so it follows the transport).
    pub(super) contact_generated: bool,
}

impl UaEngine {
    /// The initial INVITE was just sent to one of several targets.
    pub(super) fn failover_armed(&mut self, leg: &mut Leg, now: u64) {
        leg.ext.fo.responded = false;
        leg.ext.fo.reached = false;
        if leg.ext.fo.alternatives.is_empty() || self.cfg.failover_timeout_ms == 0 {
            leg.disarm(LegTimer::FailoverProbe);
        } else {
            let at = now.saturating_add(self.cfg.failover_timeout_ms);
            self.arm_leg(leg, LegTimer::FailoverProbe, at);
        }
    }

    /// Try the next target; false when there is none (or it's too late).
    pub(super) fn failover(&mut self, leg: &mut Leg, old: TxnId, now: u64) -> bool {
        if leg.role != Role::Uac || leg.cancel != CancelState::None || leg.ext.fo.reached || leg.remote_tag.is_some() || leg.ext.fo.alternatives.is_empty() {
            return false;
        }
        let next = leg.ext.fo.alternatives.remove(0);
        // A still-running transaction to the old target is abandoned.
        let running = self.txns.get(&old).is_some_and(|e| matches!(e.txn.state, TxState::Calling | TxState::Proceeding));
        if running {
            self.remove_txn(old);
        }
        let proto_changed = leg.invite_dest.is_some_and(|d| d.proto != next.proto);
        leg.invite_dest = Some(next);
        if leg.ext.fo.contact_generated
            && proto_changed
            && let Some(c) = self.contact_for(next.proto, leg.secure)
        {
            leg.local_contact = c;
        }
        let contact = format!("<{}>", leg.local_contact);
        let generated = leg.ext.fo.contact_generated && !leg.local_contact.is_empty();
        let ok = self.resend_invite(leg, old, now, |m| {
            if generated {
                m.set_header("Contact", contact);
            }
        });
        if ok {
            self.failover_armed(leg, now);
        }
        ok
    }

    /// No response from the current target in time.
    pub(super) fn failover_probe(&mut self, leg: &mut Leg, now: u64) {
        if leg.ext.fo.responded {
            return;
        }
        if let Some(t) = leg.invite_txn {
            self.failover(leg, t, now);
        }
    }
}
